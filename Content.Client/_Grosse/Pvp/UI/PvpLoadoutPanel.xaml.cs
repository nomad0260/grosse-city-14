using System.Linq;
using Content.Shared._Grosse.Pvp;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Grosse.Pvp.UI;

[GenerateTypedNameReferences]
public sealed partial class PvpLoadoutPanel : Robust.Client.UserInterface.Control
{
    public event Action<bool, PvpTeam?, string?>? LoadoutSelected;

    /// <summary>Короткая строка для заголовка карточки: «Повстанцы · Штурмовик» и т.п.</summary>
    public event Action<string>? SummaryChanged;

    /// <summary>Игрок выбрал готовый набор — карточку можно свернуть.</summary>
    public event Action? CollapseRequested;

    private bool _enabled;
    private bool _open;
    private PvpTeam? _team;
    private string? _classId;
    private bool _random;
    private bool _showClassCost;
    private string _attackersName = string.Empty;
    private string _defendersName = string.Empty;
    private Dictionary<string, int> _classCounts = new();
    private List<PvpClassInfo> _attackersClasses = new();
    private List<PvpClassInfo> _defendersClasses = new();

    public PvpLoadoutPanel()
    {
        RobustXamlLoader.Load(this);

        AttackersButton.OnPressed += _ => SelectTeam(PvpTeam.Attackers);
        DefendersButton.OnPressed += _ => SelectTeam(PvpTeam.Defenders);
        RandomButton.OnPressed += _ => SelectRandom();
    }

    /// <summary>Раскрывает или сворачивает меню. Видимо только когда режим активен.</summary>
    public void SetOpen(bool open)
    {
        _open = open;
        UpdateVisibility();
    }

    public void UpdateState(PvpLobbyStateEvent state)
    {
        _enabled = state.Enabled;
        UpdateVisibility();
        if (!state.Enabled)
            return;

        _attackersName = state.AttackersName;
        _defendersName = state.DefendersName;

        AttackersButton.Text = $"{state.AttackersName}  {state.AttackersCount}";
        DefendersButton.Text = $"{state.DefendersName}  {state.DefendersCount}";

        _random = state.RandomSelected;
        _team = state.SelectedTeam;
        _classId = state.SelectedClass;
        _showClassCost = state.ShowClassCost;
        _classCounts = new Dictionary<string, int>(state.ClassCounts);
        _attackersClasses = state.AttackersClasses;
        _defendersClasses = state.DefendersClasses;

        AttackersButton.Pressed = !_random && _team == PvpTeam.Attackers;
        DefendersButton.Pressed = !_random && _team == PvpTeam.Defenders;
        RandomButton.Pressed = _random;

        RebuildClasses();
        SummaryChanged?.Invoke(BuildSummary());
    }

    /// <summary>На узкой панели команды становятся в один столбец.</summary>
    public void SetCompact(bool compact)
    {
        TeamButtons.Columns = compact ? 1 : 2;
    }

    private void UpdateVisibility()
    {
        var visible = _enabled && _open;
        MenuPanel.Visible = visible;
        Visible = visible;
    }

    private void SelectTeam(PvpTeam team)
    {
        _random = false;
        _team = team;
        _classId = null;
        RebuildClasses();
        LoadoutSelected?.Invoke(false, team, null);
        SummaryChanged?.Invoke(BuildSummary());
    }

    private void SelectRandom()
    {
        _random = true;
        _team = null;
        _classId = null;
        RebuildClasses();
        LoadoutSelected?.Invoke(true, null, null);
        SummaryChanged?.Invoke(BuildSummary());
        CollapseRequested?.Invoke();
    }

    private void SelectClass(string id)
    {
        if (_team == null)
            return;

        _random = false;
        _classId = id;
        LoadoutSelected?.Invoke(false, _team, id);
        SummaryChanged?.Invoke(BuildSummary());
        CollapseRequested?.Invoke();
    }

    private string BuildSummary()
    {
        if (_random)
            return Loc.GetString("pvp-lobby-summary-random");

        if (_team is { } team)
        {
            var teamName = team == PvpTeam.Attackers ? _attackersName : _defendersName;
            if (string.IsNullOrEmpty(teamName))
                return Loc.GetString("pvp-lobby-summary-team");

            if (!string.IsNullOrEmpty(_classId))
            {
                var classes = team == PvpTeam.Attackers ? _attackersClasses : _defendersClasses;
                var selected = classes.FirstOrDefault(c => c.Id == _classId);
                if (selected != null)
                    return $"{teamName} · {selected.Name}";
            }

            return teamName;
        }

        return Loc.GetString("pvp-lobby-summary-empty");
    }

    private void RebuildClasses()
    {
        ClassScroll.Visible = !_random && _team != null;
        ClassList.RemoveAllChildren();
        if (!ClassScroll.Visible || _team == null)
            return;

        var classes = _team == PvpTeam.Attackers ? _attackersClasses : _defendersClasses;
        foreach (var proto in classes)
        {
            var id = proto.Id;
            var available = IsClassAvailable(id, proto.MaxCount);
            var label = _showClassCost
                ? $"{proto.Name}  ({Loc.GetString("pvp-lobby-cost", ("cost", proto.Cost))})"
                : proto.Name;
            var button = new Button
            {
                Text = label,
                ToolTip = available ? proto.Description : Loc.GetString("pvp-lobby-class-full"),
                ToggleMode = true,
                Pressed = _classId == id,
                Disabled = !available,
                HorizontalExpand = true,
                MinHeight = 28,
                StyleClasses = { "PvpClassButton" },
            };
            button.OnPressed += _ => SelectClass(id);
            ClassList.AddChild(button);
        }
    }

    private bool IsClassAvailable(string id, int maxCount)
    {
        if (maxCount <= 0)
            return true;

        if (_classId == id)
            return true;

        return _classCounts.GetValueOrDefault(id) < maxCount;
    }
}
