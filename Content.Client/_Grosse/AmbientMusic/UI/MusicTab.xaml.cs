using Content.Client.Audio;
using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Grosse.AmbientMusic.UI;

/// <summary>
///     Music player for the city ambience: what is playing right now, pause, track switching and the volume.
/// </summary>
/// <remarks>
///     Playback itself belongs to <see cref="GrosseAmbientMusicSystem"/>, which keeps running outside this tab.
///     The tab only reads its state every frame and forwards the button presses, so closing the options window
///     does not interrupt the bed.
/// </remarks>
[GenerateTypedNameReferences]
// The base type is spelled out because inside Content.Client._Grosse the name Control resolves to the namespace
// Content.Client._Grosse.Control, which hides Robust.Client.UserInterface.Control.
public sealed partial class MusicTab : Robust.Client.UserInterface.Control
{
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IEntityManager _entManager = default!;

    private readonly GrosseAmbientMusicSystem _ambience;

    public MusicTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _ambience = _entManager.System<GrosseAmbientMusicSystem>();

        var volume = Control.AddOptionPercentSlider(
            CCVars.AmbientMusicVolume,
            SliderVolume,
            scale: ContentAudioSystem.AmbientMusicMultiplier);

        // The bed reacts to this CVar live, so the slider should be audible before "save & apply".
        volume.ImmediateValueChanged += value => _cfg.SetCVar(CCVars.AmbientMusicVolume, value);

        PreviousButton.OnPressed += _ => _ambience.PlayPreviousTrack();
        PauseButton.OnPressed += _ => _ambience.TogglePause();
        NextButton.OnPressed += _ => _ambience.SkipTrack();

        Control.Initialize();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        UpdateTrackLabels(_ambience.CurrentTrack);

        var length = _ambience.TrackLength;
        var position = _ambience.TrackPosition;

        if (length > TimeSpan.Zero)
        {
            TrackProgress.MaxValue = (float) length.TotalSeconds;
            TrackProgress.Value = (float) Math.Clamp(position.TotalSeconds, 0d, length.TotalSeconds);
            LengthLabel.Text = FormatTime(length);
        }
        else
        {
            TrackProgress.MaxValue = 1f;
            TrackProgress.Value = 0f;
            LengthLabel.Text = "--:--";
        }

        PositionLabel.Text = FormatTime(position);

        PauseButton.Text = Loc.GetString(_ambience.IsPausedByPlayer
            ? "ui-options-player-play"
            : "ui-options-player-pause");

        StateLabel.Text = Loc.GetString(_ambience.IsPlaying
            ? "ui-options-player-state-playing"
            : _ambience.IsPausedByPlayer
                ? "ui-options-player-state-paused"
                : "ui-options-player-state-idle");
    }

    /// <summary>
    ///     Shows the name and the artist of <paramref name="track"/>, or the idle placeholder when nothing
    ///     is loaded. Tracks the playlist has no name for get a generic title.
    /// </summary>
    private void UpdateTrackLabels(ResPath? track)
    {
        if (track == null)
        {
            TrackLabel.Text = Loc.GetString("ui-options-player-nothing");
            ArtistLabel.Visible = false;
            return;
        }

        if (!AmbientTrackInfo.TryGet(track.Value, out var info))
        {
            TrackLabel.Text = Loc.GetString("ui-options-player-track-unknown");
            ArtistLabel.Visible = false;
            return;
        }

        TrackLabel.Text = info.Title;
        ArtistLabel.Text = info.Year == null
            ? info.Artist
            : $"{info.Artist} · {info.Year}";
        ArtistLabel.Visible = true;
    }

    private static string FormatTime(TimeSpan time)
    {
        return $"{(int) time.TotalMinutes:00}:{time.Seconds:00}";
    }
}
