        OutputValue.Text = $"{_shownOutput:0.00} MW";
    }

    private void UpdateSystems(ContainmentConsoleState state, bool manual)
    {
        var activeProjectors = 0;

        for (var i = 0; i < _rows.Length; i++)
        {
            var row = _rows[i];
            var present = i < state.Projectors.Count;
            var info = present ? state.Projectors[i] : null;

            if (info is { Enabled: true, HasCartridge: true } &&
                info.Integrity > 0.05f && info.CartridgeResource > 0f)
                activeProjectors++;

            var healthColor = QualityColor(info?.Integrity ?? 0f, 0.6f, 0.25f);
            var coolantRatio = info == null || info.HeatLoad <= 0.01f
                ? 1f
                : Math.Clamp(info.CoolantCapacity / info.HeatLoad, 0f, 1f);
            var cartridgeRatio = info is { HasCartridge: true, CartridgeMaxResource: > 0f }
                ? Math.Clamp(info.CartridgeResource / info.CartridgeMaxResource, 0f, 1f)
                : 0f;
            row.Bar.MaxValue = 100f;
            row.Bar.Value = (info?.Integrity ?? 0f) * 100f;
            row.Bar.FillColor = healthColor;

            row.Index.Text = $"{i + 1}";
            row.Health.Text = info == null ? "—" : $"{info.Integrity * 100f:0}%";
            row.Health.FontColorOverride = info == null ? MutedColor : healthColor;
            row.Cartridge.Text = info == null
                ? "—"
                : info.HasCartridge
                    ? $"{info.CartridgeName} {cartridgeRatio * 100f:0}%"
                    : "нет патрона";
            row.Cartridge.FontColorOverride = info == null
                ? MutedColor
                : info.HasCartridge
                    ? TextColor
                    : Color.FromHex(BadHex);

            row.CoolantBar.MaxValue = 100f;
            row.CoolantBar.Value = info == null ? 0f : coolantRatio * 100f;
            row.CartridgeBar.MaxValue = 100f;
            row.CartridgeBar.Value = cartridgeRatio * 100f;
            row.Coolant.Text = info == null ? "—" : info.CoolantName;
            row.Coolant.FontColorOverride = info == null
                ? MutedColor
                : coolantRatio >= 0.999f
                    ? BlueColor
                    : Color.FromHex(BadHex);

            row.Toggle.Disabled = !manual || !present;
            row.Slider.Disabled = !manual || !present;
            row.Minus.Disabled = !manual || !present;
            row.Plus.Disabled = !manual || !present;

            if (info != null)
            {
                row.Toggle.Pressed = info.Enabled;
                row.Toggle.Text = info.Enabled ? "ВКЛ" : "ВЫКЛ";

                var serverIntensity = (int) MathF.Round(info.Intensity);
                var localHold = _intensityHoldUntil[i] > _timing.CurTime;

                if (!localHold || serverIntensity == _localIntensity[i])
                {
                    _intensityHoldUntil[i] = TimeSpan.Zero;
                    _localIntensity[i] = serverIntensity;
                    row.Slider.SetValueWithoutEvent(serverIntensity);
                }

                var intensityValue = row.Slider.Value;
                row.Intensity.Text = $"{intensityValue:0}";
                row.Intensity.FontColorOverride = intensityValue > 150f
                    ? Color.FromHex(BadHex)
                    : intensityValue > 100f
                        ? Color.FromHex(WarnHex)
                        : TextColor;
            }
            else
            {
                row.Toggle.Pressed = false;
                row.Toggle.Text = "—";
                row.Slider.SetValueWithoutEvent(0f);
                row.Intensity.Text = "—";
            }
        }

        for (var i = 0; i < FieldPreview.EmitterOutput.Length; i++)
        {
            FieldPreview.EmitterOutput[i] = i < state.Projectors.Count && state.Projectors[i].Enabled
                ? state.Projectors[i].Intensity
                : 0f;
        }

        ProjectorsCountLabel.SetMarkup(state.Projectors.Count == 0
            ? $"[color={IdleHex}]не найдены[/color]"
            : $"активно [color={GoodHex}]{activeProjectors}[/color] из {state.Projectors.Count}");

        var compressionColor = state.Compression > state.CompressionThreshold ? WarnHex : AccentHex;
        CompressionBar.MaxValue = MathF.Max(1f, state.CompressionThreshold * 1.5f);
        CompressionBar.Value = state.Compression;
        CompressionBar.FillColor = Color.FromHex(compressionColor);
        CompressionValue.SetMarkup($"плотность [color={AccentHex}]{state.Density:0}[/color]/200");

        FieldPreview.Compression = state.Compression;
        FieldPreview.CompressionThreshold = state.CompressionThreshold;
        FieldPreview.Expansion = state.Expansion;
        FieldPreviewLabel.SetMarkup(
            $"сжатие [color={compressionColor}]{state.Compression:0}/{state.CompressionThreshold:0}[/color]");
        FieldPreviewStats.SetMarkup(
            $"стабильность [color={Quality(state.Stability, 75f, 40f)}]{state.Stability:0}[/color] · " +
            $"сдерживание [color={Quality(state.ContainmentIntegrity, 75f, 40f)}]" +
            $"{state.ContainmentIntegrity:0}[/color] · расширение {state.Expansion:0}/200");

        ContainmentWarning.SetMarkup(BuildContainmentWarning(state));

        CoolingStatusLabel.SetMarkup(
            $"эффективность [color={Quality(state.CoolingEfficiency, 0.75f, 0.4f)}]" +
            $"{state.CoolingEfficiency:P0}[/color] · " +
            $"{state.HeatInput:0}/{state.CoolingCapacity:0} ед.");
        CoolingBar.MaxValue = 100f;
        CoolingBar.Value = state.CoolingEfficiency * 100f;
        CoolingBar.FillColor = state.CoolingEfficiency >= 0.75f
            ? Color.FromHex(GoodHex)
            : Color.FromHex(WarnHex);

        CoolingHint.SetMarkup(!state.Running
            ? "Реактор остановлен. Охлаждение не требуется."
            : state.CoolingEfficiency >= 0.75f
                ? "Охлаждение справляется с текущей тепловой нагрузкой."
                : $"[color={WarnHex}]Охлаждение не успевает отводить тепло. Снизьте интенсивность эмиттеров.[/color]");
    }

    private void UpdateSettings(ContainmentConsoleState state, bool power)
    {
        PowerSlider.SetValueWithoutEvent(state.PowerScale * 100f);
        PowerSlider.Disabled = !power || !state.CorePresent;
        PowerBar.MaxValue = 300f;
        PowerBar.Value = state.PowerScale * 100f;
        var powerColor = state.PowerScale > 1f ? WarnHex : AccentHex;
        PowerBar.FillColor = Color.FromHex(powerColor);
        PowerValue.SetMarkup(
            $"ядра [color={powerColor}]{state.PowerScale * 100f:0}%[/color] · " +
            $"выработка {state.EnergyOutput:0} кВт");

        PowerHint.SetMarkup(!state.Running
            ? "Реактор остановлен. Запустите его, чтобы подать мощность в сеть."
            : state.PowerScale > 1.001f
                ? $"[color={WarnHex}]Форсирование: энергии больше, но эмиттеры греются и изнашиваются быстрее, " +
                  $"растёт фон, падает стабильность и проседает сдерживание.[/color]"
                : state.EnergyOutput >= state.EnergyLoad
                    ? "Выработка покрывает нагрузку сети."
                    : $"[color={WarnHex}]Выработка ниже нагрузки — сеть тянет энергию из запасов.[/color]");

        PowerLoadLabel.SetMarkup(
            $"выработка [color={AccentHex}]{state.EnergyOutput / 1000f:0.00}[/color] MW · " +
            $"нагрузка {state.EnergyLoad / 1000f:0.00} MW");

        var loadCoverage = state.EnergyLoad <= 0.01f
            ? 100f
            : Math.Clamp(state.EnergyOutput / state.EnergyLoad * 100f, 0f, 100f);
        LoadBalanceBar.MaxValue = 100f;
        LoadBalanceBar.Value = loadCoverage;
        LoadBalanceBar.FillColor = loadCoverage >= 99f ? Color.FromHex(GoodHex) : Color.FromHex(WarnHex);

        var maxRadiation = MathF.Max(1f, state.MaxRadiation);
        var radiationColor = state.Radiation > maxRadiation * 0.5f
            ? BadHex
            : state.Radiation > maxRadiation * 0.1f
                ? WarnHex
                : GoodHex;
        RadiationValue.SetMarkup($"[color={radiationColor}]{state.Radiation:0}[/color] рад/с");
        RadiationBar.MaxValue = maxRadiation;
        RadiationBar.Value = state.Radiation;
        RadiationBar.FillColor = Color.FromHex(radiationColor);

    }

    private void UpdateActionButtons(ContainmentConsoleState state, bool full)
    {
