        CoreToggleButton.Disabled = !canStart;
        CoreToggleButton.Text = "▶  Запустить ядро";
        StyleButton(CoreToggleButton, canStart ? _startButton : _startButtonDisabled,
            canStart ? Color.FromHex(GoodHex) : MutedColor);
        StartHint.Text = !state.CorePresent
            ? "Нет связи с ядром"
            : state.Running
                ? "Ядро уже работает"
                : "Готово к пуску";
        StartHint.Visible = true;

        var canScram = full && state.CorePresent && state.Running;
        var armed = canScram && _scramArmedUntil > _timing.CurTime;
        ScramButton.Disabled = !canScram;
        ScramButton.Text = armed ? "⚠  Подтвердить сброс" : "■  Аварийный сброс";
        StyleButton(ScramButton, canScram ? _scramButton : _scramButtonDisabled,
            canScram ? Color.FromHex(BadHex) : MutedColor);
        ScramHint.Text = !canScram
            ? "Недоступно"
            : armed
                ? "Нажмите ещё раз в течение 3 секунд"
                : "Необратимая остановка";
        ScramHint.Visible = true;
    }

