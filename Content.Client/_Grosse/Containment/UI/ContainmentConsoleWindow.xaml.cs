    /// <summary>
    /// Аварийный сброс требует подтверждения: случайный клик не должен
    /// глушить реактор и снимать 15% исправности с эмиттеров.
    /// </summary>
    private void TryScram()
    {
        var now = _timing.CurTime;

        if (now < _scramArmedUntil)
        {
            _scramArmedUntil = TimeSpan.Zero;
            OnEmergencyStop?.Invoke(false);
            return;
        }

        _scramArmedUntil = now + TimeSpan.FromSeconds(3);
        ScramButton.Text = "⚠  Подтвердить сброс";
        ScramHint.Text = "Нажмите ещё раз в течение 3 секунд";
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        var dt = args.DeltaSeconds;

        AnimateValues(dt);
        AnimateClock();
        AnimateWarning(dt);
        AnimatePage(dt);
        AnimateAftermath(dt);
    }

    /// <summary>
    /// Цифры на карточках плавно доезжают до нового значения,
    /// а резкое падение стабильности или скачок температуры дают красную вспышку.
    /// </summary>
    private void AnimateValues(float dt)
    {
        if (!_valuesInitialized)
            return;

        var speed = Math.Clamp(dt * 9f, 0f, 1f);

        // На сбитом сигнале цифры доезжают рывками.
        if (_aftermath)
            speed *= 0.15f + 0.85f * (1f - _glitchBurst);

        if (_targetStability < _shownStability - 1.5f ||
            (_temperatureLive && _targetTemp > _shownTemp + 25f))
        {
            _valueFlash = 1f;
        }

        _shownStability += (_targetStability - _shownStability) * speed;
        _shownContainment += (_targetContainment - _shownContainment) * speed;
        _shownTemp += (_targetTemp - _shownTemp) * speed;
        _shownOutput += (_targetOutput - _shownOutput) * speed;

        if (MathF.Abs(_targetStability - _shownStability) > 0.005f ||
            MathF.Abs(_targetContainment - _shownContainment) > 0.005f ||
            MathF.Abs(_targetTemp - _shownTemp) > 0.005f ||
            MathF.Abs(_targetOutput - _shownOutput) > 0.0005f)
        {
            WriteValueText();
        }

        _valueFlash = MathF.Max(0f, _valueFlash - dt * 1.8f);
        var color = Color.InterpolateBetween(TextColor, Color.FromHex(BadHex), _valueFlash);
        StabilityValue.FontColorOverride = color;
        TempValue.FontColorOverride = color;
        ContainmentValue.FontColorOverride = color;
        OutputValue.FontColorOverride = color;
    }

    private void AnimateClock()
    {
        if (_timing.CurTime - _lastClock < TimeSpan.FromSeconds(1))
            return;

        _lastClock = _timing.CurTime;
        ClockLabel.Text = FormatClock(_timing.CurTime);
    }

    private void AnimateWarning(float dt)
    {
        if (!WarningPanel.Visible || _warningColor == null)
            return;

        var color = _warningColor.Value;
        _warningPulse += dt;
        var pulse = 0.5f + 0.5f * MathF.Sin(_warningPulse * 4.2f);
        _warningBox.BackgroundColor = color.WithAlpha(0.05f + 0.06f * pulse);
        _warningAccent.BackgroundColor = color.WithAlpha(0.55f + 0.45f * pulse);
    }

    private void AnimatePage(float dt)
    {
        if (_pageFade >= 1f)
            return;

        _pageFade = Math.Clamp(_pageFade + dt * 5f, 0f, 1f);
        Tabs.Modulate = Color.White.WithAlpha(_pageFade);
    }

    private void BeginAftermath()
    {
        _aftermath = true;
        _glitchBurst = 1f;
        _jitterPhase = 0f;
        _nextGlitchBurst = _timing.CurTime + TimeSpan.FromMilliseconds(_random.Next(400, 1200));
        _uiFrozenUntil = _timing.CurTime + TimeSpan.FromMilliseconds(_random.Next(400, 900));
        CrtOverlay.Glitch = 0.7f;
        ApplyGlitchText();
    }

    private void EndAftermath()
    {
        _aftermath = false;
        _glitchBurst = 0f;
        _uiFrozenUntil = TimeSpan.Zero;
        CrtOverlay.Glitch = 0f;
        Shell.Modulate = Color.White;
        _shellOffsetX = float.NaN;
        _shellOffsetY = float.NaN;
        SetShellOffset(0f, 0f);
    }

    /// <summary>
    /// Последствия катастрофы: всплески помех, тряска и мерцание всего экрана.
    /// Во время всплеска состояние «зависает» — это и есть лаги интерфейса.
    /// </summary>
    private void AnimateAftermath(float dt)
    {
        if (!_aftermath)
            return;

        var now = _timing.CurTime;

        if (now >= _nextGlitchBurst)
        {
            _glitchBurst = 1f;
            _nextGlitchBurst = now + TimeSpan.FromMilliseconds(_random.Next(450, 1500));
            _uiFrozenUntil = now + TimeSpan.FromMilliseconds(_random.Next(200, 700));

            if (_random.Prob(0.5f))
                ApplyGlitchText();
        }

        _glitchBurst = MathF.Max(0f, _glitchBurst - dt * 1.6f);

        var burst = _glitchBurst;
        _jitterPhase += dt * (9f + 26f * burst);

        // Тряска: содержимое экрана уезжает, не меняя размеров.
        var amplitude = 1f + 6f * burst;
        SetShellOffset(
            MathF.Round(MathF.Sin(_jitterPhase * 7.1f) * amplitude),
            MathF.Round(MathF.Cos(_jitterPhase * 5.3f) * amplitude));

        // Мерцание: экран то проседает, то вспыхивает.
        var flicker = 0.78f + 0.22f * (0.5f + 0.5f * MathF.Sin(_jitterPhase * 3.4f));

        if (burst > 0.55f)
            flicker *= 0.30f + 0.70f * _random.NextFloat();

        Shell.Modulate = Color.White.WithAlpha(Math.Clamp(flicker, 0.12f, 1f));
        CrtOverlay.Glitch = 0.35f + 0.65f * burst;

        // Часы сбиты вместе с остальным интерфейсом.
        if (burst > 0.3f)
            ClockLabel.Text = Scramble(FormatClock(_timing.CurTime));
    }

    private void SetShellOffset(float x, float y)
    {
        // Сдвиг меняет только смещение, размер остаётся прежним; лишнюю переверстку не гоним.
        if (MathF.Abs(x - _shellOffsetX) < 0.5f && MathF.Abs(y - _shellOffsetY) < 0.5f)
            return;

        _shellOffsetX = x;
        _shellOffsetY = y;
        LayoutContainer.SetMarginLeft(Shell, x);
        LayoutContainer.SetMarginRight(Shell, -x);
        LayoutContainer.SetMarginTop(Shell, y);
        LayoutContainer.SetMarginBottom(Shell, -y);
    }

    private static readonly char[] GlitchGlyphs =
    {
        '#', '%', '&', '@', '?', '!', '~', '*', '+', '=', '|', '/', '\\', '<', '>', '0', '1', '7', '9',
    };

    private string Scramble(string text)
    {
        var chars = text.ToCharArray();

        for (var i = 0; i < chars.Length; i++)
        {
            if (chars[i] == ':' || chars[i] == '.' || chars[i] == ' ')
                continue;

            if (_random.Prob(0.35f))
                chars[i] = GlitchGlyphs[_random.Next(GlitchGlyphs.Length)];
        }

        return new string(chars);
    }

    /// <summary>«Баги» интерфейса: заголовки и предупреждение на время всплеска теряют буквы.</summary>
    private void ApplyGlitchText()
    {
        RunningLabel.SetMarkup($"[color={BadHex}]{Scramble("СИГНАЛ ПОТЕРЯН")}[/color]");
        ModeTitle.Text = Scramble("Реактор");
        ModeSubtitle.Text = Scramble("Центральный реактор станции");

        if (WarningPanel.Visible)
            WarningLabel.SetMarkup($"[color={BadHex}]{Scramble("Нет связи с ядром. Канал повреждён.")}[/color]");
    }

    protected override void Opened()
    {
        base.Opened();

        var screen = UserInterfaceManager.RootControl.Size;

        if (screen.Y <= 0f)
            return;

        var width = MathF.Min(1320f, MathF.Max(1180f, screen.X - 32f));
        var height = MathF.Min(820f, MathF.Max(660f, screen.Y - 24f));
        SetSize = new Vector2(width, height);
        RecenterWindow(new Vector2(0.5f, 0.5f));
    }

    public void UpdateState(ContainmentConsoleState state)
    {
        if (state.Aftermath && !_aftermath)
            BeginAftermath();
        else if (_aftermath && !state.Aftermath && state.CorePresent)
            EndAftermath();

        // «Лаги»: во время всплеска помех часть пакетов теряется, и цифры застывают.
        if (_aftermath && _timing.CurTime < _uiFrozenUntil)
            return;

        _updating = true;
        _running = state.Running;
        ClockLabel.Text = FormatClock(_timing.CurTime);

        var full = state.Mode == ReactorConsoleMode.Full;
        var manual = full || state.Mode == ReactorConsoleMode.Manual;
        var containment = full || state.Mode == ReactorConsoleMode.Containment;
        var power = full || state.Mode == ReactorConsoleMode.Power;
        var diagnostic = full || state.Mode == ReactorConsoleMode.Diagnostic;

        if (_lastMode != state.Mode)
        {
            _lastMode = state.Mode;
            ShowPage(state.Mode switch
            {
                ReactorConsoleMode.Manual or ReactorConsoleMode.Containment => 1,
                ReactorConsoleMode.Power => 2,
                _ => 0,
            });

            if (state.Mode == ReactorConsoleMode.Diagnostic)
                ShowView(1);
        }

        UpdateHeader(state);
        UpdateDashboard(state);

        if (state.CorePresent)
            UpdateSystems(state, manual);
        else
            ClearProjectors();

        UpdateSettings(state, power);
        UpdateActionButtons(state, full);

        NavSystems.Disabled = !(manual || containment || power || diagnostic);
        NavSettings.Disabled = !(power || full);

        if (state.CorePresent)
        {
            var maxEnergy = MathF.Max(1f, state.MaxEnergyOutput);
            var maxTemperature = MathF.Max(1f, state.MaxTemperature);
            var maxRadiation = MathF.Max(1f, state.MaxRadiation);
            var temperatureRatio = Math.Clamp(state.Temperature / maxTemperature * 100f, 0f, 100f);
            var energyRatio = Math.Clamp(state.EnergyOutput / maxEnergy * 100f, 0f, 100f);

            TelemetryGraph.Push(state.Stability, temperatureRatio, energyRatio);
            EnergySpark.Push(energyRatio);

            StabilityLegendValue.Text = $"{state.Stability:0.0}%";
            TempLegendValue.Text = state.Running ? $"{state.Temperature:0.0} K" : "—";
            EnergyLegendValue.Text = $"{state.EnergyOutput / 1000f:0.00} MW";

            DashboardDiagnosticsLabel.SetMarkup(
                $"Ядро [color={Quality(state.Stability, 75f, 40f)}]{state.Stability:0.0}/100[/color] · " +
                $"поле [color={Quality(state.ContainmentIntegrity, 75f, 40f)}]" +
                $"{state.ContainmentIntegrity:0.0}/100[/color] · " +
                $"радиация {state.Radiation:0} рад/с · " +
                $"эмиттеры {CountActiveProjectors(state)}/{state.Projectors.Count}");
        }
        else
        {
            StabilityLegendValue.Text = "—";
            TempLegendValue.Text = "—";
            EnergyLegendValue.Text = "—";
            DashboardDiagnosticsLabel.SetMarkup($"[color={BadHex}]Нет связи с ядром.[/color]");
        }

        _updating = false;
    }

    private void UpdateHeader(ContainmentConsoleState state)
    {
        var (title, subtitle) = state.Mode switch
        {
            ReactorConsoleMode.Full => ("Реактор", "Центральный реактор станции"),
            ReactorConsoleMode.Manual => ("Эмиттеры", "Контур стабилизации ядра"),
            ReactorConsoleMode.Containment => ("Поле", "Камера сдерживания"),
            ReactorConsoleMode.Power => ("Мощность", "Энергия и нагрузка"),
            ReactorConsoleMode.Diagnostic => ("Журнал", "Диагностика реактора"),
            _ => ("РТМ", "Терминал управления"),
        };

        ModeTitle.Text = title;
        ModeSubtitle.Text = subtitle;

        var statusColor = !state.CorePresent
            ? BadHex
            : !state.Running
                ? IdleHex
                : state.CoreState == ContainmentCoreState.Nominal
                    ? GoodHex
                    : BadHex;
        var status = !state.CorePresent
            ? "Нет связи"
            : !state.Running
                ? "Система остановлена"
                : state.CoreState == ContainmentCoreState.Nominal
                    ? "Система в норме"
                    : "Система нестабильна";

        RunningLabel.SetMarkup($"[color={statusColor}]{status}[/color]");
        HealthDot.Color = Color.FromHex(statusColor);
        HealthDot.Danger = state.CorePresent && state.Running &&
                           state.CoreState != ContainmentCoreState.Nominal;
        HealthDot.Active = state.CorePresent && state.Running;

        _chipBox.BackgroundColor = Color.FromHex(!state.CorePresent
            ? "#291917"
            : state.CoreState == ContainmentCoreState.Nominal && state.Running
                ? "#0D211D"
                : "#101B1D");
        _chipBox.BorderColor = Color.FromHex(!state.CorePresent
            ? "#743830"
            : state.CoreState == ContainmentCoreState.Nominal && state.Running
                ? "#2A5B4C"
                : "#28404A");
    }

    private void UpdateDashboard(ContainmentConsoleState state)
    {
        var stabilityColor = QualityColor(state.Stability, 75f, 40f);
        var containmentColor = QualityColor(state.ContainmentIntegrity, 75f, 40f);
        var tempColor = QualityColor(1f - state.Temperature / MathF.Max(1f, state.MaxTemperature), 0.5f, 0.2f);
        var maxEnergy = MathF.Max(1f, state.MaxEnergyOutput);
        var maxTemperature = MathF.Max(1f, state.MaxTemperature);

        var hasLiveTemperature = state.CorePresent && state.Running;

        StabilityBar.MaxValue = 100f;
        StabilityBar.Value = state.Stability;
        StabilityBar.FillColor = stabilityColor;
        ContainmentBar.MaxValue = 100f;
        ContainmentBar.Value = state.ContainmentIntegrity;
        ContainmentBar.FillColor = containmentColor;
        TempBar.MaxValue = 100f;
        TempBar.Value = hasLiveTemperature
            ? Math.Clamp(state.Temperature / maxTemperature * 100f, 0f, 100f)
            : 0f;
        TempBar.FillColor = tempColor;

        _targetStability = state.Stability;
        _targetContainment = state.ContainmentIntegrity;
        _targetTemp = hasLiveTemperature ? state.Temperature : 0f;
        _targetOutput = state.EnergyOutput / 1000f;
        _temperatureLive = hasLiveTemperature;

        if (!_valuesInitialized)
        {
            _shownStability = _targetStability;
            _shownContainment = _targetContainment;
            _shownTemp = _targetTemp;
            _shownOutput = _targetOutput;
            _valuesInitialized = true;
        }

        WriteValueText();


        CoreView.Running = state.Running;
        CoreView.Danger = state.Running &&
                          (state.CoreState is ContainmentCoreState.Expanding
                              or ContainmentCoreState.Compressing
                              or ContainmentCoreState.ContainmentFailure
                              or ContainmentCoreState.Meltdown
                              or ContainmentCoreState.Singularity ||
                           state.Temperature >= 700f);
        CoreView.Warning = state.Running &&
                           !CoreView.Danger &&
                           (state.CoreState is ContainmentCoreState.Overload
                               or ContainmentCoreState.Unstable ||
                            state.Temperature >= 500f ||
                            state.Stability < 70f);
        CoreView.Starting = state.Running &&
                            state.CoreState == ContainmentCoreState.Initialization;
        CoreView.Stability = state.Stability;
        CoreView.Temperature = state.Temperature;
        CoreView.Energy = state.EnergyOutput;

        CrtOverlay.Danger = CoreView.Danger;
        SetWarning(state);
    }

