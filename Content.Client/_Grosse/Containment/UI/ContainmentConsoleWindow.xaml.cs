    private void SetWarning(ContainmentConsoleState state)
    {
        var (text, hex) = BuildWarning(state);

        // Потеря связи — тоже предупреждение: без этого условия панель оставалась
        // видимой, но пустой, потому что текст для неё не выставлялся.
        var visible = !state.CorePresent ||
                      state.CoreState != ContainmentCoreState.Nominal ||
                      state.Temperature >= 300f ||
                      state.Compression > state.CompressionThreshold;
        var color = Color.FromHex(hex);

        WarningPanel.Visible = visible;

        if (!visible)
        {
            WarningLabel.SetMarkup("");
            _warningColor = null;
            return;
        }

        WarningLabel.SetMarkup($"[color={hex}]{text}[/color]");
        _warningColor = color;
        _warningBox.BackgroundColor = color.WithAlpha(0.08f);
        _warningBox.BorderColor = color.WithAlpha(0.55f);
        _warningAccent.BackgroundColor = color;
    }

    private static (string Text, string Hex) BuildWarning(ContainmentConsoleState state)
    {
        if (!state.CorePresent)
            return ("Нет связи с ядром. Проверьте питание терминала и расстояние до ядра.", BadHex);

        if (state.CoreState == ContainmentCoreState.Nominal)
        {
            if (state.Temperature >= 900f)
                return ("КРИТИЧЕСКАЯ ТЕМПЕРАТУРА: оборудование разрушается. Немедленно остановите реактор.", BadHex);
            if (state.Temperature >= 700f)
                return ("Температура выше 700 K: эмиттеры и вспомогательные системы получают повреждения.", BadHex);
            if (state.Temperature >= 500f)
                return ("Температура выше 500 K: эффективность эмиттеров снижена.", WarnHex);
            if (state.Temperature >= 300f)
                return ("Температура выше 300 K: проверьте охлаждение.", WarnHex);
        }

        if (state.CoreState == ContainmentCoreState.Compressing)
        {
            return ($"Критическое сжатие. До коллапса {state.CollapseTimeRemaining:0.0} с. " +
                    "Немедленно снизьте интенсивность эмиттеров или мощность поля.", BadHex);
        }

        if (state.Compression > state.CompressionThreshold)
        {
            return ($"Сжатие выше нормы: {state.Compression:0} / {state.CompressionThreshold:0}. " +
                    "Снизьте эмиттеры или замените Дигамму — коллапса пока нет.", WarnHex);
        }

        return state.CoreState switch
        {
            ContainmentCoreState.Expanding =>
                (state.Running
                    ? "Ядро расширяется. Проверьте патроны и поднимите стабилизацию эмиттеров."
                    : "Ядро не остыло и продолжает расширяться. Остудите контур, иначе распад.", BadHex),
            ContainmentCoreState.ContainmentFailure =>
                ("Сдерживание потеряно. Реактор вот-вот расплавится.", BadHex),
            ContainmentCoreState.Overload =>
                ("Выработка ниже нагрузки сети. Снизьте нагрузку или поднимите мощность ядра.", WarnHex),
            ContainmentCoreState.Unstable =>
                ("Стабильность ниже нормы. Проверьте патроны, включение и исправность эмиттеров.", WarnHex),
            ContainmentCoreState.Initialization =>
                ("Идёт первичная стабилизация ядра.", WarnHex),
            ContainmentCoreState.Offline =>
                ("Реактор остановлен.", IdleHex),
            ContainmentCoreState.Meltdown or ContainmentCoreState.Singularity =>
                ("Катастрофа. Установка разрушена.", BadHex),
            _ => ("Все системы в норме.", GoodHex),
        };
    }

    private static string BuildContainmentWarning(ContainmentConsoleState state)
    {
        if (!state.Running)
            return $"[color={IdleHex}]Реактор остановлен. Сдерживание не требуется.[/color]";

        if (state.CoreState == ContainmentCoreState.Compressing)
            return $"[color={BadHex}]Критическое сжатие. Снизьте эмиттеры или замените Дигамму.[/color]";

        if (state.Compression > state.CompressionThreshold)
            return $"[color={WarnHex}]Сжатие выше нормы. Снизьте эмиттеры или замените Дигамму.[/color]";

        if (state.ContainmentIntegrity < 75f)
            return $"[color={WarnHex}]Сдерживание ниже нормы. Проверьте поле и охлаждение.[/color]";

        return $"[color={MutedColor.ToHex()}]Сдерживание в норме.[/color]";
    }

    private static int CountActiveProjectors(ContainmentConsoleState state)
    {
        var active = 0;

        foreach (var info in state.Projectors)
        {
            if (info.Enabled && info.HasCartridge && info.Integrity > 0.05f && info.CartridgeResource > 0f)
                active++;
        }

        return active;
    }

    private static string FormatClock(TimeSpan time)
    {
        var totalSeconds = Math.Max(0, (int) time.TotalSeconds);
        return $"{totalSeconds / 3600 % 24:00}:{totalSeconds / 60 % 60:00}:{totalSeconds % 60:00}";
    }

    private static void StyleButton(Button button, RoundedStyleBox box, Color textColor)
    {
        button.StyleBoxOverride = box;
        button.Label.FontColorOverride = textColor;
    }

    private static RoundedStyleBox Dot(Color color)
    {
        return new RoundedStyleBox
        {
            BackgroundColor = color,
            BorderColor = color,
            BorderThickness = 0f,
            CornerRadius = 4f,
        };
    }

    private static RoundedStyleBox ButtonBox(string background, string border, float radius)
    {
        return ButtonBox(Color.FromHex(background), Color.FromHex(border), radius);
    }

    private static RoundedStyleBox ButtonBox(Color background, Color border, float radius)
    {
        return new RoundedStyleBox
        {
            BackgroundColor = background,
            BorderColor = border,
            BorderThickness = 1f,
            CornerRadius = radius,
            Padding = new Thickness(8f, 4f, 8f, 4f),
        };
    }

    private static RoundedStyleBox Card(Color background, Color border, float radius)
    {
        return new RoundedStyleBox
        {
            BackgroundColor = background,
            BorderColor = border,
            BorderThickness = 1f,
            CornerRadius = radius,
        };
    }

    private static RoundedStyleBox MakeTrack()
    {
        return new RoundedStyleBox
        {
            BackgroundColor = Color.FromHex("#0A0607"),
            BorderColor = Color.FromHex("#2C1517"),
            BorderThickness = 1f,
            CornerRadius = 4f,
            Padding = new Thickness(0f, 4f, 0f, 4f),
        };
    }

    private static RoundedStyleBox MakeFill(Color color)
    {
        return new RoundedStyleBox
        {
            BackgroundColor = color,
            BorderColor = color,
            BorderThickness = 1f,
            CornerRadius = 4f,
            Padding = new Thickness(0f, 4f, 0f, 4f),
        };
    }

    private static Color QualityColor(float value, float good, float warn)
    {
        return Color.FromHex(Quality(value, good, warn));
    }

    private static string Quality(float value, float good, float warn)
    {
        return value >= good ? GoodHex : value >= warn ? WarnHex : BadHex;
    }
