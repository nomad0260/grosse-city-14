namespace Content.Client._Grosse.Lobby.UI;

/// <summary>
/// Чёрно-красный брифинг, который показывается при входе в лобби: что это за
/// сервер, управление, правила, лор, быт города, роли, антагонисты, отыгрыш и
/// быстрый старт. Окно модальное — пока игрок его не закроет, клики по лобби
/// не проходят.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class LobbyTutorialWindow : LayoutContainer
{
    private const int PageCount = 9;

    /// <summary>Длительность проявления всего окна при открытии, в секундах.</summary>
    private const float OpenFadeDuration = 0.18f;

    /// <summary>Длительность затухания окна при закрытии, в секундах.</summary>
    private const float CloseFadeDuration = 0.12f;

    /// <summary>Длительность перелистывания одной страницы.</summary>
    private const float PageFadeDuration = 0.16f;

    /// <summary>Смещение страницы в пикселях в начале перелистывания.</summary>
    private const float PageSlide = 12f;

    /// <summary>Отступ окна от краёв экрана.</summary>
    private const float ScreenPadding = 32f;

    /// <summary>Пределы ширины окна: на узком экране оно сжимается, на широком не растягивается.</summary>
    private const float MinCardWidth = 760f;
    private const float MaxCardWidth = 1180f;

    /// <summary>Пределы высоты окна: на низком экране страницы прокручиваются внутри.</summary>
    private const float MinCardHeight = 460f;
    private const float MaxCardHeight = 780f;

    /// <summary>Ширина колонки-оглавления слева.</summary>
    private const float RailWidth = 252f;

    /// <summary>Ширина канта между оглавлением и страницей.</summary>
    private const float RailEdgeWidth = 1f;

    /// <summary>Поля правой колонки: 24 px с каждой стороны плюс рамка окна.</summary>
    private const float RightPanePadding = 50f;

    /// <summary>Отступ текста от кнопки-ключа в таблице управления.</summary>
    private const float BindKeyWidth = 130f;

    private static readonly string[] PageTitleKeys =
    [
        "lobby-tutorial-basics-title",
        "lobby-tutorial-controls-title",
        "lobby-tutorial-rules-title",
        "lobby-tutorial-lore-title",
        "lobby-tutorial-life-title",
        "lobby-tutorial-roles-title",
        "lobby-tutorial-antag-title",
        "lobby-tutorial-rp-title",
        "lobby-tutorial-start-title",
    ];

    private readonly BoxContainer[] _pages;
    private readonly LobbyMenuButton[] _nav;
    private readonly Label[] _navLabels;

    private int _page;

    // Прозрачность всего окна: 0 — скрыто, 1 — полностью видно.
    private float _fade = 1f;
    private float _fadeTarget = 1f;

    // Прогресс перелистывания текущей страницы: 1 — анимация закончена.
    private float _pageAnim = 1f;
    private int _slideDirection = 1;

    public LobbyTutorialWindow()
    {
        RobustXamlLoader.Load(this);

        // Затемнение занимает весь экран: окно центрируется относительно лобби,
        // а не прилипает к углу при любом разрешении.
        LayoutContainer.SetAnchorPreset(Dim, LayoutContainer.LayoutPreset.Wide);
        LayoutContainer.SetMarginLeft(Dim, 0f);
        LayoutContainer.SetMarginTop(Dim, 0f);
        LayoutContainer.SetMarginRight(Dim, 0f);
        LayoutContainer.SetMarginBottom(Dim, 0f);

        _pages =
        [
            Page0, Page1, Page2, Page3, Page4,
            Page5, Page6, Page7, Page8,
        ];

        _nav = new LobbyMenuButton[PageCount];
        _navLabels = new Label[PageCount];

        for (var i = 0; i < PageCount; i++)
            BuildNavEntry(i);

        PrevButton.OnPressed += _ => SetPage(_page - 1, -1);
        NextButton.OnPressed += _ =>
        {
            if (_page >= PageCount - 1)
                Close();
            else
                SetPage(_page + 1, 1);
        };
        SkipButton.OnPressed += _ => Close();

        // «Больше не показывать»: запоминаем выбор в конфиге клиента, чтобы
        // брифинг не всплывал при следующих заходах в лобби.
        NeverButton.OnPressed += _ =>
        {
            IoCManager.Resolve<IConfigurationManager>()
                .SetCVar(GrosseCVars.LobbyTutorialDisabled, true);
            Close();
        };

        OnResized += UpdateResponsiveLayout;
        UpdateResponsiveLayout();

        SetPage(0, 1, false);
    }

    /// <summary>
    /// Пункт оглавления: номер, название раздела и узкая плашка-кнопка.
    /// Активный пункт подсвечивается в <see cref="SetPage"/>.
    /// </summary>
    private void BuildNavEntry(int index)
    {
        var number = new Label
        {
            Text = $"{index + 1:D2}",
            VerticalAlignment = VAlignment.Center,
        };
        number.SetOnlyStyleClass("LobbyTutorialStep");

        var title = new Label
        {
            Text = Loc.GetString(PageTitleKeys[index]),
            VerticalAlignment = VAlignment.Center,
            HorizontalExpand = true,
            ClipText = true,
        };
        title.SetOnlyStyleClass("LobbyTutorialNavLabel");
        _navLabels[index] = title;

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 10,
            Margin = new Thickness(12f, 0f, 8f, 0f),
        };
        row.AddChild(number);
        row.AddChild(title);

        var button = new LobbyMenuButton
        {
            MinHeight = 34f,
            HorizontalExpand = true,
            BaseLeftMargin = 12f,
            RailX = 4f,
            AccentColor = Color.FromHex("#D13239"),
        };
        button.AddChild(row);

        // Замыкание хранит собственный индекс: у каждой кнопки он свой.
        var page = index;
        button.OnPressed += _ => SetPage(page, page > _page ? 1 : -1);

        _nav[index] = button;
        NavList.AddChild(button);
    }

    /// <summary>
    /// Ставит окно ровно по центру экрана и вписывает его в доступную высоту.
    /// Позиция считается вручную, без CenterContainer: если контент выше
    /// экрана, контейнерное центрирование уводит окно вниз и вбок.
    /// </summary>
    private void UpdateResponsiveLayout()
    {
        var width = Math.Clamp(Size.X - ScreenPadding * 2f, MinCardWidth, MaxCardWidth);
        var height = Math.Clamp(Size.Y - ScreenPadding * 2f, MinCardHeight, MaxCardHeight);

        TutorialPanel.MinWidth = width;
        TutorialPanel.MaxWidth = width;
        TutorialPanel.MinHeight = height;
        TutorialPanel.MaxHeight = height;

        LayoutContainer.SetAnchorPreset(TutorialPanel, LayoutContainer.LayoutPreset.TopLeft);

        var offsetX = MathF.Max(0f, (Size.X - width) * 0.5f);
        var offsetY = MathF.Max(0f, (Size.Y - height) * 0.5f);

        LayoutContainer.SetMarginLeft(TutorialPanel, offsetX);
        LayoutContainer.SetMarginRight(TutorialPanel, offsetX);
        LayoutContainer.SetMarginTop(TutorialPanel, offsetY);
        LayoutContainer.SetMarginBottom(TutorialPanel, offsetY);

        // Абзацы переносятся по ширине правой колонки, а таблица клавиш
        // отдаёт часть ширины плашке с клавишей.
        var textWidth = width - RailWidth - RailEdgeWidth - RightPanePadding;
        foreach (var page in _pages)
        {
            foreach (var child in page.Children)
                child.MaxWidth = textWidth;
        }

        foreach (var row in Binds.Children)
        {
            foreach (var cell in row.Children)
            {
                if (cell is RichTextLabel bind)
                    bind.MaxWidth = textWidth - BindKeyWidth;
            }
        }
    }

    /// <summary>Показывает брифинг с первой страницы и проявляет затемнение.</summary>
    public void Open()
    {
        SetPage(0, 1, false);
        BodyScroll.SetScrollValue(Vector2.Zero);
        Visible = true;
        UpdateResponsiveLayout();

        if (LobbyFx.ReducedMotion)
        {
            _fade = 1f;
            _fadeTarget = 1f;
            Modulate = Color.White;
            return;
        }

        _fade = 0f;
        _fadeTarget = 1f;
        Modulate = Color.White.WithAlpha(0f);
    }

    /// <summary>
    /// Закрывает брифинг: при выключенном «уменьшении движения» мгновенно,
    /// иначе коротким затуханием.
    /// </summary>
    public void Close()
    {
        if (!Visible)
            return;

        if (LobbyFx.ReducedMotion)
        {
            HideImmediately();
            return;
        }

        _fadeTarget = 0f;
    }

    private void HideImmediately()
    {
        Visible = false;
        _fade = 1f;
        _fadeTarget = 1f;
        Modulate = Color.White;
    }

    private void SetPage(int page, int direction, bool animate = true)
    {
        _page = Math.Clamp(page, 0, PageCount - 1);

        for (var i = 0; i < _pages.Length; i++)
            _pages[i].Visible = i == _page;

        for (var i = 0; i < _nav.Length; i++)
        {
            var active = i == _page;
            _nav[i].IsActive = active;
            _navLabels[i].SetOnlyStyleClass(active
                ? "LobbyTutorialNavLabelActive"
                : "LobbyTutorialNavLabel");
        }

        PageTitle.Text = Loc.GetString(PageTitleKeys[_page]);
        StepLabel.Text = Loc.GetString("lobby-tutorial-step",
            ("current", $"{_page + 1:D2}"),
            ("total", $"{PageCount:D2}"));
        NextLabel.Text = Loc.GetString(_page >= PageCount - 1
            ? "lobby-tutorial-finish"
            : "lobby-tutorial-next");
        PrevButton.Disabled = _page == 0;

        BodyScroll.SetScrollValue(Vector2.Zero);

        // Перелистывание: новая страница проявляется и подъезжает по вертикали.
        // Вперёд — снизу вверх, назад — сверху вниз.
        if (!animate || LobbyFx.ReducedMotion || !Visible)
        {
            _pageAnim = 1f;
            Pages.Modulate = Color.White;
            Pages.Margin = new Thickness(0f);
            return;
        }

        _slideDirection = direction;
        _pageAnim = 0f;
        Pages.Modulate = Color.White.WithAlpha(0f);
        Pages.Margin = new Thickness(0f, PageSlide * direction, 0f, 0f);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        UpdateFade(args.DeltaSeconds);
        UpdatePageAnimation(args.DeltaSeconds);
    }

    private void UpdateFade(float deltaSeconds)
    {
        if (MathF.Abs(_fadeTarget - _fade) <= 0.001f)
            return;

        var duration = _fadeTarget > _fade ? OpenFadeDuration : CloseFadeDuration;
        _fade = Math.Clamp(_fade + MathF.Sign(_fadeTarget - _fade) * deltaSeconds / duration, 0f, 1f);
        Modulate = Color.White.WithAlpha(_fade);

        if (_fade > 0f)
            return;

        // Затухание закончилось — окно убирается и готово к следующему открытию.
        HideImmediately();
    }

    private void UpdatePageAnimation(float deltaSeconds)
    {
        if (_pageAnim >= 1f)
            return;

        _pageAnim = MathF.Min(1f, _pageAnim + deltaSeconds / PageFadeDuration);
        var eased = Easings.OutQuad(_pageAnim);

        Pages.Modulate = Color.White.WithAlpha(eased);
        Pages.Margin = new Thickness(0f, PageSlide * _slideDirection * (1f - eased), 0f, 0f);

        if (_pageAnim < 1f)
            return;

        Pages.Modulate = Color.White;
        Pages.Margin = new Thickness(0f);
    }
}
