[GenerateTypedNameReferences]
public sealed partial class ResearchTerminalWindow : FancyWindow
{
    public event Action<string>? OnSynthesize;
    public event Action<string, EffectGraph>? OnSaveFormula;
    public event Action<string>? OnLoadFormula;
    public event Action<string, string>? OnRenameFormula;
    public event Action<string>? OnDeleteFormula;
    public event Action<string>? OnCopyFormula;
    public event Action<string, EffectGraph>? OnCrystallize;
    public event Action<string, EffectGraph>? OnReflashCrystal;
    public event Action<string, EffectGraph>? OnTest;

    private const string AccentHex = "#4FC3F7";
    private const string GoodHex = "#5BE38F";
    private const string WarnHex = "#FFC266";
    private const string BadHex = "#FF6B6B";
    private const string MutedHex = "#8EA3B8";

    private static readonly Color CardColor = Color.FromHex("#131C27");
    private static readonly Color InsetColor = Color.FromHex("#0F1721");
    private static readonly Color BorderColor = Color.FromHex("#253346");

    private readonly RoundedStyleBox _headerAccent = new() { CornerRadius = 2f };
    private readonly RoundedStyleBox _statusAccent = new() { CornerRadius = 2f };

    private ResearchTerminalState? _state;
    private string _selectedFormulaId = string.Empty;
    private int _lastRevision = -1;
    private NodeEditorControl _graphEditor = default!;

    public ResearchTerminalWindow()
    {
        RobustXamlLoader.Load(this);

        _graphEditor = new NodeEditorControl
        {
            HorizontalExpand = true,
            VerticalExpand = true,
        };
        GraphHost.AddChild(_graphEditor);

        TabContainer.SetTabTitle(WorkbenchTab, "Материал");
        TabContainer.SetTabTitle(ConstructorTab, "Конструктор");
        TabContainer.SetTabTitle(ArchiveTab, "Архив");

        SynthesizeButton.OnPressed += _ => OnSynthesize?.Invoke(SampleNameEdit.Text);
        SaveFormulaButton.OnPressed += _ => SaveDraft();
        CrystallizeButton.OnPressed += _ => Crystallize();
        ReflashCrystalButton.OnPressed += _ => ReflashCrystal();
        TestButton.OnPressed += _ => Test();
        DeleteNodeButton.OnPressed += _ => _graphEditor.RemoveSelectedNode();
        RenameFormulaButton.OnPressed += _ =>
        {
            if (!string.IsNullOrEmpty(_selectedFormulaId))
                OnRenameFormula?.Invoke(_selectedFormulaId, RenameFormulaEdit.Text);
        };
        ClearGraphButton.OnPressed += _ =>
        {
            _graphEditor.SetGraph(new EffectGraph());
            UpdateValidation();
        };

        _graphEditor.GraphChanged += UpdateValidation;
        _graphEditor.NodeSelected += _ => RebuildInspector();
        _graphEditor.StatusMessage += message => StatusLabel.SetMarkup(message);

        PaletteSearch.OnTextChanged += _ => BuildPalette(PaletteSearch.Text);
        BuildPalette();
        RebuildInspector();
        UpdateValidation();

        ApplyTheme();
    }

    private void ApplyTheme()
    {
        HeaderPanel.PanelOverride = CardBox(CardColor);
        HeaderAccent.PanelOverride = _headerAccent;
        _headerAccent.BackgroundColor = Color.FromHex(AccentHex);

        StatusCard.PanelOverride = CardBox(InsetColor);
        StatusAccent.PanelOverride = _statusAccent;
        _statusAccent.BackgroundColor = Color.FromHex(AccentHex);

        SynthesisCard.PanelOverride = CardBox(CardColor);
        AnalyzerCard.PanelOverride = CardBox(CardColor);
        WorkOrderCard.PanelOverride = CardBox(InsetColor);

        ConstructorHeaderCard.PanelOverride = CardBox(CardColor);
        PaletteCard.PanelOverride = CardBox(CardColor);
        GraphCard.PanelOverride = CardBox(InsetColor);
        GraphHost.PanelOverride = InsetBox();
        InspectorCard.PanelOverride = CardBox(CardColor);
        ConstructorFooterCard.PanelOverride = CardBox(CardColor);

        ArchiveHeaderCard.PanelOverride = CardBox(CardColor);
        ArchiveListCard.PanelOverride = CardBox(InsetColor);

        Tabs.PanelStyleBoxOverride = CardBox(InsetColor);
        Tabs.TabFontColorOverride = Color.FromHex(AccentHex);
        Tabs.TabFontColorInactiveOverride = Color.FromHex(MutedHex);

        SynthesizeButton.AddStyleClass(StyleClass.Positive);
        CrystallizeButton.AddStyleClass(StyleClass.Positive);
        SaveFormulaButton.AddStyleClass(StyleClass.Positive);
        DeleteNodeButton.AddStyleClass(StyleClass.Negative);
        ClearGraphButton.AddStyleClass(StyleClass.Negative);
    }

    protected override void Opened()
    {
        base.Opened();

        var screen = UserInterfaceManager.RootControl.Size;

        if (screen.Y <= 0f)
            return;

        var width = MathF.Min(1400f, MathF.Max(1100f, screen.X - 40f));
        var height = MathF.Max(720f, screen.Y - 24f);
        SetSize = new Vector2(width, height);
        RecenterWindow(new Vector2(0.5f, 0.5f));
    }

    private static RoundedStyleBox CardBox(Color background)
    {
        return new RoundedStyleBox
        {
            BackgroundColor = background,
            BorderColor = BorderColor,
            BorderThickness = 1f,
            CornerRadius = 10f,
        };
    }

    private static RoundedStyleBox InsetBox()
    {
        return new RoundedStyleBox
        {
            BackgroundColor = InsetColor,
            BorderColor = BorderColor,
            BorderThickness = 1f,
            CornerRadius = 8f,
        };
    }

    public void UpdateState(ResearchTerminalState state)
    {
        _state = state;
        _selectedFormulaId = state.SelectedFormulaId;
        RenameFormulaButton.Disabled = string.IsNullOrEmpty(_selectedFormulaId);

        // The status contains player-authored formula names; escape it before rich-text parsing.
        StatusLabel.SetMarkup(FormattedMessage.EscapeText(state.Status));

        RequiredLabel.SetMarkup(
            $"Заказ: жидкость — {Requirement(state.RequiredLiquidName)} (10 ед.) · " +
            $"сырьё — {Requirement(state.RequiredOreName)} (1 шт.) · сгусток — 1 шт.");

        LoadedLabel.SetMarkup(
            $"Загружено: жидкость — {Loaded(state.HasLiquid, state.LiquidMatches, state.LiquidName)} · " +
            $"сырьё — {Loaded(state.HasOre, state.OreMatches, state.OreName)} · " +
            $"сгусток — {Loaded(state.HasClot, state.HasClot, state.ClotName)}");

        RebuildFeeds(state);
        ClotLabel.SetMarkup($"Сгусток: {Loaded(state.HasClot, state.HasClot, state.ClotName)}");

        SynthesisLabel.SetMarkup(string.IsNullOrEmpty(state.LastSynthesis)
            ? "Последний синтез: —"
            : $"Последний синтез: {FormattedMessage.EscapeText(state.LastSynthesis)}");

        SynthesizeButton.Disabled = !state.SynthesizerPresent ||
                                    !state.HasLiquid || !state.LiquidMatches ||
                                    !state.HasOre || !state.OreMatches ||
                                    !state.HasClot;

        AnalysisHint.SetMarkup(!state.AnalyzerPresent
            ? "Анализатор не найден в радиусе действия."
            : state.AnalyzerHasCrystal
                ? "В анализаторе кристалл. Проверьте его состояние и при необходимости перепрошейте новой формулой."
                : state.MaterialStats.Count == 0
                    ? "Вставьте образец в анализатор, чтобы увидеть его характеристики."
                    : "Характеристики образца в анализаторе.");

        RebuildAnalysis(state.MaterialStats);
        RebuildArchive(state.Formulas);

        WorkHint.SetMarkup(
            $"КС-1: {(state.HasLiquid && state.LiquidMatches && state.HasOre && state.OreMatches && state.HasClot ? "[color=#5BE38F]заказ собран, можно синтезировать[/color]" : "[color=#FFC266]загрузите компоненты по заказу[/color]")} · " +
            $"Анализатор: {(state.HasMaterial ? "[color=#5BE38F]образец установлен[/color]" : "[color=#8EA3B8]нужен образец для кристалла[/color]")}");

        if (state.Revision != _lastRevision)
        {
            _lastRevision = state.Revision;
            _graphEditor.SetGraph(state.Draft);
            RebuildInspector();
        }

        UpdateValidation();
    }

    private void SaveDraft()
    {
        var graph = _graphEditor.Graph;
        if (!EffectGraphValidator.Validate(graph, out var errors))
        {
            StatusLabel.SetMarkup(FormattedMessage.EscapeText(string.Join(" ", errors)));
            return;
        }

        OnSaveFormula?.Invoke(FormulaNameEdit.Text, graph.Clone());
    }

    private void Crystallize()
    {
        var graph = _graphEditor.Graph;
        if (!EffectGraphValidator.Validate(graph, out var errors))
        {
            StatusLabel.SetMarkup(FormattedMessage.EscapeText(string.Join(" ", errors)));
            return;
        }

        OnCrystallize?.Invoke(FormulaNameEdit.Text, graph.Clone());
    }

    private void ReflashCrystal()
    {
        var graph = _graphEditor.Graph;
        if (!EffectGraphValidator.Validate(graph, out var errors))
        {
            StatusLabel.SetMarkup(FormattedMessage.EscapeText(string.Join(" ", errors)));
            return;
        }

        OnReflashCrystal?.Invoke(FormulaNameEdit.Text, graph.Clone());
    }

    private void Test()
    {
        var graph = _graphEditor.Graph;
        if (!EffectGraphValidator.Validate(graph, out var errors))
        {
            StatusLabel.SetMarkup(FormattedMessage.EscapeText(string.Join(" ", errors)));
            return;
        }

        OnTest?.Invoke(FormulaNameEdit.Text, graph.Clone());
    }

    private void UpdateValidation()
    {
        var graph = _graphEditor.Graph;
        var valid = EffectGraphValidator.Validate(graph, out var errors);

        ValidationLabel.SetMarkup(valid
            ? $"[color=#5BE38F]Формула корректна · {graph.Nodes.Count} узлов, {graph.Connections.Count} связей[/color]"
            : string.Join("\n", errors.Take(6).Select(error => $"[color=#FF6B6B]• {error}[/color]")));

        SaveFormulaButton.Disabled = !valid || graph.Nodes.Count == 0;
        CrystallizeButton.Disabled = !valid || graph.Nodes.Count == 0 ||
            _state is not { HasMaterial: true } || _state is { AnalyzerHasCrystal: true };
        ReflashCrystalButton.Disabled = !valid || graph.Nodes.Count == 0 ||
            _state is not { AnalyzerHasCrystal: true };
        TestButton.Disabled = !valid || graph.Nodes.Count == 0;
        DeleteNodeButton.Disabled = _graphEditor.SelectedNodeId < 0;
        ClearGraphButton.Disabled = graph.Nodes.Count == 0;
    }

    private void RebuildFeeds(ResearchTerminalState state)
    {
        FeedRows.RemoveAllChildren();
        FeedRows.AddChild(BuildFeedCard(state.LiquidFeed));
        FeedRows.AddChild(BuildFeedCard(state.OreFeed));
    }

    private static Robust.Client.UserInterface.Control BuildFeedCard(ResearchFeedInfo feed)
    {
        var card = new PanelContainer
        {
            PanelOverride = InsetBox(),
            HorizontalExpand = true,
        };

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 10,
            Margin = new Thickness(10, 8),
        };

        var iconPrototype = feed.HasItem && !string.IsNullOrEmpty(feed.LoadedPrototype)
            ? feed.LoadedPrototype
            : feed.IconPrototype;
        var icon = new EntityPrototypeView
        {
            SetSize = new Vector2(48f),
            Stretch = SpriteView.StretchMode.Fill,
            Scale = new Vector2(1.5f),
        };
        if (!string.IsNullOrEmpty(iconPrototype))
            icon.SetPrototype(iconPrototype);

        // The liquid has no entity prototype of its own, so tint a beaker with its palette colour.
        if (!feed.HasItem || feed.Title == "Жидкость")
            icon.Modulate = Color.FromHex(feed.Color, Color.White);

        row.AddChild(icon);

        var info = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 2,
        };
        info.AddChild(new Label
        {
            Text = string.IsNullOrEmpty(feed.Name) ? $"{feed.Title}: —" : $"{feed.Title}: {feed.Name}",
            ClipText = true,
            ToolTip = feed.Name,
            FontColorOverride = Color.FromHex("#E8F1FA"),
        });
        info.AddChild(new Label
        {
            Text = $"ID: {DisplayValue(feed.PoolId)}",
            ClipText = true,
            FontColorOverride = Color.FromHex("#8EA3B8"),
        });
        info.AddChild(new Label
        {
            Text = $"{feed.ContentLabel}: {DisplayValue(feed.ContentId)}",
            ClipText = true,
            FontColorOverride = Color.FromHex("#B6C4D4"),
        });
        info.AddChild(new Label
        {
            Text = feed.HasItem
                ? $"Загружено: {feed.LoadedName} · ID: {DisplayValue(feed.LoadedPrototype)}"
                : "Загружено: —",
            ClipText = true,
            FontColorOverride = feed.HasItem
                ? feed.Matches ? Color.FromHex("#5BE38F") : Color.FromHex("#FF6B6B")
                : Color.FromHex("#6B7A8C"),
        });
        row.AddChild(info);
        card.AddChild(row);
        return card;
    }

    private static string DisplayValue(string value)
    {
        return string.IsNullOrEmpty(value) ? "—" : value;
    }

    private void RebuildAnalysis(IReadOnlyList<MaterialStatEntry> entries)
    {
        AnalysisRows.RemoveAllChildren();

        if (entries.Count == 0)
        {
            AnalysisRows.AddChild(new Label
            {
                Text = "Нет данных.",
                FontColorOverride = Color.FromHex("#8EA3B8"),
            });
            return;
        }

        foreach (var entry in entries)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                SeparationOverride = 8,
            };
            row.AddChild(new Label
            {
                Text = entry.Label,
                MinWidth = 160,
                FontColorOverride = Color.FromHex("#B6C4D4"),
            });
            row.AddChild(new Label
            {
                Text = entry.Value,
                HorizontalExpand = true,
                FontColorOverride = Color.White,
            });
            AnalysisRows.AddChild(row);
        }
    }

    private void RebuildArchive(IReadOnlyList<ResearchFormulaInfo> formulas)
    {
        ArchiveRows.RemoveAllChildren();
        ArchiveHint.SetMarkup(formulas.Count == 0
            ? "Архив пуст. Соберите формулу в конструкторе и сохраните её."
            : $"Сохранено формул: {formulas.Count}. Загрузка создаёт копию в конструкторе.");

        foreach (var formula in formulas)
        {
            var card = new PanelContainer
            {
                PanelOverride = InsetBox(),
                HorizontalExpand = true,
            };

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                SeparationOverride = 8,
                Margin = new Thickness(10, 6),
            };

            var tests = formula.TestCount == 0
                ? "испытаний нет"
                : $"испытаний: {formula.TestCount}" + (formula.Reproducible ? " · воспроизводима" : "");
            row.AddChild(new Label
            {
                Text = $"{formula.Name} · v{formula.Version} · {formula.NodeCount} узлов · {formula.Author} · {tests}",
                HorizontalExpand = true,
                ClipText = true,
                MinWidth = 300,
                FontColorOverride = Color.FromHex("#E8F1FA"),
            });

            var load = new Button { Text = "Загрузить" };
            var id = formula.Id;
            load.OnPressed += _ => OnLoadFormula?.Invoke(id);
            row.AddChild(load);

            var copy = new Button { Text = "Копия" };
            copy.OnPressed += _ => OnCopyFormula?.Invoke(id);
            row.AddChild(copy);

            var delete = new Button { Text = "Удалить" };
            delete.AddStyleClass(StyleClass.Negative);
            delete.OnPressed += _ => OnDeleteFormula?.Invoke(id);
            row.AddChild(delete);

            card.AddChild(row);
            ArchiveRows.AddChild(card);
        }
    }

    private void BuildPalette(string? filter = null)
    {
        PaletteRows.RemoveAllChildren();
        var search = (filter ?? string.Empty).Trim();
        var shown = 0;

        foreach (var group in EffectOperationCatalog.Grouped())
        {
            var operations = group.Where(operation => Matches(operation, search)).ToList();
            if (operations.Count == 0)
                continue;

            var heading = new Label
            {
                Text = group.Key.ToUpperInvariant(),
                FontColorOverride = Color.FromHex("#4FC3F7"),
                Margin = new Thickness(0, 4, 0, 1),
            };
            PaletteRows.AddChild(heading);

            foreach (var operation in operations)
            {
                shown++;
                var button = new Button
                {
                    Text = operation.Label,
                    HorizontalExpand = true,
                    ToolTip = $"{operation.Description}\n{operation.Id}",
                };
                var id = operation.Id;
                button.OnPressed += _ => _graphEditor.AddNode(id);
                PaletteRows.AddChild(button);
            }
        }

        PaletteCount.Text = search.Length == 0
            ? $"Операторов: {EffectOperationCatalog.All.Count}"
            : $"Найдено: {shown} из {EffectOperationCatalog.All.Count}";
    }

    private static bool Matches(EffectOperationInfo operation, string search)
    {
        if (search.Length == 0)
            return true;

        return operation.Label.Contains(search, StringComparison.OrdinalIgnoreCase) ||
               operation.Description.Contains(search, StringComparison.OrdinalIgnoreCase) ||
               operation.Category.Contains(search, StringComparison.OrdinalIgnoreCase) ||
               operation.Id.Contains(search, StringComparison.OrdinalIgnoreCase);
    }

    private void RebuildInspector()
    {
        ParameterRows.RemoveAllChildren();

        var selected = _graphEditor.Graph.FindNode(_graphEditor.SelectedNodeId);
        if (selected == null)
        {
            SelectedNodeLabel.Text = "Узел не выбран";
            ParameterRows.AddChild(new Label
            {
                Text = "Выберите узел на рабочей области.",
                FontColorOverride = Color.FromHex("#8EA3B8"),
            });
            return;
        }

        var definition = EffectOperationCatalog.Get(selected.Operation);
        if (definition == null)
        {
            SelectedNodeLabel.Text = $"Неизвестная операция · узел {selected.Id}";
            ParameterRows.AddChild(new Label
            {
                Text = "Операция отсутствует в каталоге. Удалите узел и добавьте корректный.",
                FontColorOverride = Color.FromHex("#FF6B6B"),
                ClipText = false,
            });
            DeleteNodeButton.Disabled = false;
            return;
        }

        SelectedNodeLabel.Text = $"{definition.Label} · узел {selected.Id}";
        ParameterRows.AddChild(new Label
        {
            Text = definition.Description,
            FontColorOverride = Color.FromHex("#B6C4D4"),
            ClipText = false,
        });

        if (definition.Parameters.Length == 0)
        {
            ParameterRows.AddChild(new Label
            {
                Text = "У этой операции нет параметров.",
                FontColorOverride = Color.FromHex("#8EA3B8"),
            });
            return;
        }

        foreach (var parameter in definition.Parameters)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                SeparationOverride = 2,
                Margin = new Thickness(0, 3, 0, 0),
            };
            row.AddChild(new Label
            {
                Text = parameter.Label,
                FontColorOverride = Color.FromHex("#B6C4D4"),
            });

            var spin = new FloatSpinBox(parameter.Step, 2)
            {
                HorizontalExpand = true,
                Value = selected.Parameters.GetValueOrDefault(parameter.Id, parameter.Default),
            };
            spin.IsValid = value => value >= parameter.Min && value <= parameter.Max;

            var nodeId = selected.Id;
            var parameterId = parameter.Id;
            spin.OnValueChanged += args =>
            {
                _graphEditor.SetParameter(nodeId, parameterId, args.Value);
                UpdateValidation();
            };

            row.AddChild(spin);
            ParameterRows.AddChild(row);
        }

        DeleteNodeButton.Disabled = false;
    }

    private static string Requirement(string name)
    {
        return string.IsNullOrEmpty(name)
            ? "[color=#8EA3B8]—[/color]"
            : $"[color=#4FC3F7]{FormattedMessage.EscapeText(name)}[/color]";
    }

    private static string Loaded(bool present, bool matches, string name)
    {
        if (!present)
            return "[color=#6B7A8C]нет[/color]";

        var color = matches ? "#5BE38F" : "#FF6B6B";
        return $"[color={color}]{FormattedMessage.EscapeText(name)}[/color]";
    }
