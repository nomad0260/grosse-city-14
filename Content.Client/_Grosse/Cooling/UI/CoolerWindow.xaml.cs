using System;
using Content.Client.UserInterface.Controls;
using Content.Shared._Grosse.Cooling;
using Content.Shared.Chemistry.Reagent;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;
using Robust.Shared.IoC;
using Robust.Shared.Prototypes;

namespace Content.Client._Grosse.Cooling.UI;

[GenerateTypedNameReferences]
public sealed partial class CoolerWindow : FancyWindow
{
    public event Action? OnInsertCoolant;
    public event Action? OnEjectCoolant;
    public event Action? OnFill;
    public event Action? OnInsertWaste;
    public event Action? OnEjectWaste;
    public event Action? OnDrainWaste;
    public event Action? OnDrainAll;

    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IPrototypeManager _prototype = default!;

    // Индикация: зелёный — норма, янтарный — внимание, красный — авария.
    private static readonly Color GoodColor = Color.FromHex("#43DD85");
    private static readonly Color WarnColor = Color.FromHex("#F5A623");
    private static readonly Color BadColor = Color.FromHex("#FF6961");
    private static readonly Color MutedColor = Color.FromHex("#8A7676");
    private static readonly Color TrackColor = Color.FromHex("#140B0C");

    // Заливка шкал создаётся один раз: в UpdateState меняется только цвет.
    private readonly StyleBoxFlat _coolantFill = new() { BackgroundColor = GoodColor };
    private readonly StyleBoxFlat _wasteFill = new() { BackgroundColor = WarnColor };

    public CoolerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        InsertCoolantButton.OnPressed += _ => OnInsertCoolant?.Invoke();
        EjectCoolantButton.OnPressed += _ => OnEjectCoolant?.Invoke();
        InsertWasteButton.OnPressed += _ => OnInsertWaste?.Invoke();
        EjectWasteButton.OnPressed += _ => OnEjectWaste?.Invoke();

        FillButton.OnPressed += _ => OnFill?.Invoke();
        DrainWasteButton.OnPressed += _ => OnDrainWaste?.Invoke();
        DrainAllButton.OnPressed += _ => OnDrainAll?.Invoke();

        CoolantBar.BackgroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = TrackColor };
        CoolantBar.ForegroundStyleBoxOverride = _coolantFill;
        WasteBar.BackgroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = TrackColor };
        WasteBar.ForegroundStyleBoxOverride = _wasteFill;
    }

    public void UpdateState(CoolerBoundUserInterfaceState state)
    {
        CoolantBar.MinValue = 0f;
        CoolantBar.MaxValue = Math.Max(1f, state.MaxVolume);
        CoolantBar.Value = state.Volume;

        WasteBar.MinValue = 0f;
        WasteBar.MaxValue = Math.Max(1f, state.MaxWaste);
        WasteBar.Value = state.Waste;

        CoolantVolumeLabel.Text = $"{state.Volume:0} / {state.MaxVolume:0} ед.";
        WasteLabel.Text = $"{state.Waste:0} / {state.MaxWaste:0} ед.";

        // Waste — часть общего объёма бака, поэтому доля считается от Volume:
        // раньше отработка прибавлялась к объёму второй раз и загрязнение занижалось.
        var contamination = state.Volume > 0.01f
            ? state.Waste / state.Volume
            : 0f;

        CoolantLabel.Text = string.IsNullOrEmpty(state.Coolant)
            ? "бак пуст"
            : _prototype.TryIndex(state.Coolant, out ReagentPrototype? reagent)
                ? reagent.LocalizedName
                : state.Coolant;

        CoolingLabel.Text = $"{state.CoolingCapacity:0} ед./с";
        CoolingLabel.FontColorOverride = state.CoolingCapacity <= 0.01f
            ? BadColor
            : state.CoolingCapacity < 60f
                ? WarnColor
                : GoodColor;

        _wasteFill.BackgroundColor = state.Waste >= state.MaxWaste * 0.9f ? BadColor : WarnColor;

        var wasteFull = state.Waste >= state.MaxWaste;
        StatusLabel.Text = wasteFull
            ? "Отстойник полон: блок не охлаждает. Нажмите «Слить отработку»."
            : state.Waste > 0.01f
                ? $"Загрязнение {contamination:P0}. Отработку можно слить отдельно, не трогая чистый хладагент."
                : "Один блок обслуживает один эмиттер. Чистый хладагент лучше не сливать впустую.";

        StatusLabel.FontColorOverride = wasteFull ? BadColor : state.Waste > 0.01f ? WarnColor : MutedColor;

        UpdateSlot(CoolantSlotView, CoolantSlotLabel, CoolantSlotFill, state.CoolantItem,
            state.CoolantSlot, EjectCoolantButton);
        UpdateSlot(WasteSlotView, WasteSlotLabel, WasteSlotFill, state.WasteItem,
            state.WasteSlot, EjectWasteButton);

        var coolantReady = state.CoolantSlot is { } coolantSlot && coolantSlot.Volume > 0.01f;
        var tankFull = state.Volume >= state.MaxVolume - 0.01f;
        var wasteSlotFree = HasRoom(state.WasteSlot);

        FillButton.Disabled = !coolantReady || tankFull;
        DrainWasteButton.Disabled = state.Waste <= 0.01f || !wasteSlotFree;
        DrainAllButton.Disabled = state.Volume <= 0.01f || !wasteSlotFree;
    }

    private void UpdateSlot(
        SpriteView view,
        Label name,
        Label fill,
        NetEntity? item,
        FluidSlotState? slot,
        Button eject)
    {
        _entities.TryGetEntity(item, out var entity);

        view.SetEntity(entity);

        name.Text = entity is { } uid && _entities.TryGetComponent(uid, out MetaDataComponent? meta)
            ? meta.EntityName
            : "ячейка пуста";

        fill.Text = slot == null
            ? "—"
            : $"{slot.Volume:0} / {slot.MaxVolume:0} ед.";

        eject.Disabled = entity == null;
    }

    private static bool HasRoom(FluidSlotState? slot)
    {
        return slot is { } s && s.MaxVolume - s.Volume > 0.01f;
    }
}
