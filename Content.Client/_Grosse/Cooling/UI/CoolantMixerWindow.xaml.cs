using System;
using Content.Client.UserInterface.Controls;
using Content.Shared._Grosse.Cooling;
using Content.Shared.Chemistry.Reagent;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;
using Robust.Shared.IoC;
using Robust.Shared.Prototypes;

namespace Content.Client._Grosse.Cooling.UI;

[GenerateTypedNameReferences]
public sealed partial class CoolantMixerWindow : FancyWindow
{
    public event Action? OnInsertInput;
    public event Action? OnEjectInput;
    public event Action? OnInsertOutput;
    public event Action? OnEjectOutput;
    public event Action? OnPourIn;
    public event Action? OnPourOut;

    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IPrototypeManager _prototype = default!;

    // Та же индикация, что в консоли реактора: норма, внимание, авария.
    private static readonly Color GoodColor = Color.FromHex("#43DD85");
    private static readonly Color WarnColor = Color.FromHex("#F5A623");
    private static readonly Color BadColor = Color.FromHex("#FF6961");
    private static readonly Color MutedColor = Color.FromHex("#8A7676");
    private static readonly Color TrackColor = Color.FromHex("#140B0C");

    private readonly StyleBoxFlat _mixFill = new() { BackgroundColor = GoodColor };

    public CoolantMixerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        InsertInputButton.OnPressed += _ => OnInsertInput?.Invoke();
        EjectInputButton.OnPressed += _ => OnEjectInput?.Invoke();
        InsertOutputButton.OnPressed += _ => OnInsertOutput?.Invoke();
        EjectOutputButton.OnPressed += _ => OnEjectOutput?.Invoke();

        PourInButton.OnPressed += _ => OnPourIn?.Invoke();
        PourOutButton.OnPressed += _ => OnPourOut?.Invoke();

        MixBar.BackgroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = TrackColor };
        MixBar.ForegroundStyleBoxOverride = _mixFill;
    }

    public void UpdateState(CoolantMixerBoundUserInterfaceState state)
    {
        MixBar.MinValue = 0f;
        MixBar.MaxValue = Math.Max(1f, state.MaxVolume);
        MixBar.Value = state.Volume;

        VolumeLabel.Text = $"{state.Volume:0} / {state.MaxVolume:0} ед.";

        var stats = state.Stats;

        ComponentsLabel.Text = stats == null ? "компонентов: 0" : $"компонентов: {stats.Components}";
        MixtureLabel.Text = stats == null
            ? "бак пуст"
            : stats.Components > 1
                ? $"смесь из {stats.Components} жидкостей"
                : "чистая жидкость";

        UpdateStats(stats);
        UpdateBonuses(stats?.Bonuses);
        UpdateReagents(state);

        UpdateSlot(InputSlotView, InputSlotLabel, InputSlotFill, state.InputItem, state.InputSlot,
            EjectInputButton);
        UpdateSlot(OutputSlotView, OutputSlotLabel, OutputSlotFill, state.OutputItem, state.OutputSlot,
            EjectOutputButton);

        var canPourIn = state.InputSlot is { Volume: > 0.01f } && state.Volume < state.MaxVolume - 0.01f;
        var canPourOut = state.Volume > 0.01f && HasRoom(state.OutputSlot);

        PourInButton.Disabled = !canPourIn;
        PourOutButton.Disabled = !canPourOut;

        if (stats == null)
        {
            StatusLabel.Text = "Бак пуст: вставьте канистру в ячейку «Откуда» и нажмите «Влить в бак».";
            StatusLabel.FontColorOverride = MutedColor;
        }
        else if (stats.Hazardous)
        {
            StatusLabel.Text = "Опасная жидкость: при сильном загрязнении она повреждает контур охладителя.";
            StatusLabel.FontColorOverride = BadColor;
        }
        else if (stats.Components > 1)
        {
            StatusLabel.Text =
                "Смесь из нескольких жидкостей теряет около 10% теплоотвода и быстрее зарастает отработкой.";
            StatusLabel.FontColorOverride = WarnColor;
        }
        else
        {
            StatusLabel.Text = "Цифры посчитаны для одного блока охладителя РТМ на этой жидкости.";
            StatusLabel.FontColorOverride = GoodColor;
        }
    }

    private void UpdateStats(CoolantMixerStats? stats)
    {
        if (stats == null)
        {
            CapacityLabel.Text = "—";
            ConsumptionLabel.Text = "—";
            RuntimeLabel.Text = "—";
            HeatCapacityLabel.Text = "—";
            HeatTransferLabel.Text = "—";
            FlowLabel.Text = "—";
            ViscosityLabel.Text = "—";
            RadiationLabel.Text = "—";
            StabilityLabel.Text = "—";
            RangeLabel.Text = "—";
            WasteLabel.Text = "—";
            ContaminationLabel.Text = "—";

            CapacityLabel.FontColorOverride = MutedColor;
            RangeLabel.FontColorOverride = MutedColor;
            ContaminationLabel.FontColorOverride = MutedColor;
            return;
        }

        CapacityLabel.Text = $"{stats.Capacity:0} ед./с";
        CapacityLabel.FontColorOverride = stats.Capacity >= 110f
            ? GoodColor
            : stats.Capacity >= 60f
                ? WarnColor
                : BadColor;

        ConsumptionLabel.Text = $"{stats.ConsumptionPerSecond:0.00} ед./с";

        RuntimeLabel.Text = stats.RuntimeSeconds < 0f
            ? "очень долго"
            : stats.RuntimeSeconds < 120f
                ? $"{stats.RuntimeSeconds:0} с"
                : $"{stats.RuntimeSeconds / 60f:0} мин";

        HeatCapacityLabel.Text = $"{stats.HeatCapacity:0.00}";
        HeatTransferLabel.Text = $"{stats.HeatTransfer:0.00}";
        FlowLabel.Text = $"{stats.Flow:0.00}";
        ViscosityLabel.Text = $"{stats.Viscosity:0.00}";
        RadiationLabel.Text = $"{stats.RadiationResistance:0.00}";
        StabilityLabel.Text = $"{stats.Stability:0.00}";

        RangeLabel.Text = $"{stats.MinTemperatureCelsius:0}…{stats.MaxTemperatureCelsius:0} °C";
        RangeLabel.FontColorOverride = stats.MaxTemperatureCelsius >= 600f ? GoodColor : MutedColor;

        WasteLabel.Text = $"×{stats.WasteMultiplier:0.00}";

        ContaminationLabel.Text = $"{stats.Contamination:P0}";
        ContaminationLabel.FontColorOverride = stats.Contamination switch
        {
            < 0.01f => GoodColor,
            < 0.25f => WarnColor,
            _ => BadColor,
        };
    }

    /// <summary>
    /// Бонусы основной жидкости: именно по ним выбирают хладагент, поэтому
    /// показываем их даже когда остальные цифры уже хорошие.
    /// </summary>
    private void UpdateBonuses(CoolantMixerBonuses? bonuses)
    {
        if (bonuses == null)
        {
            DominantLabel.Text = "—";
            EnergyLabel.Text = "—";
            WearLabel.Text = "—";
            ToleranceLabel.Text = "—";
            StabilizationLabel.Text = "—";
            HeatGenLabel.Text = "—";

            DominantLabel.FontColorOverride = MutedColor;
            EnergyLabel.FontColorOverride = MutedColor;
            WearLabel.FontColorOverride = MutedColor;
            ToleranceLabel.FontColorOverride = MutedColor;
            StabilizationLabel.FontColorOverride = MutedColor;
            HeatGenLabel.FontColorOverride = MutedColor;
            return;
        }

        DominantLabel.Text = _prototype.TryIndex(bonuses.Coolant, out ReagentPrototype? proto)
            ? proto.LocalizedName
            : bonuses.Coolant;
        DominantLabel.FontColorOverride = MutedColor;

        EnergyLabel.Text = FormatPercent(bonuses.EnergyBonus);
        EnergyLabel.FontColorOverride = bonuses.EnergyBonus > 0.005f ? GoodColor : MutedColor;

        var wearDelta = 1f - bonuses.WearFactor;
        WearLabel.Text = Math.Abs(wearDelta) < 0.005f
            ? "без изменений"
            : wearDelta > 0f
                ? $"−{wearDelta:P0}"
                : $"+{-wearDelta:P0}";
        WearLabel.FontColorOverride = wearDelta > 0.005f
            ? GoodColor
            : wearDelta < -0.005f
                ? WarnColor
                : MutedColor;

        ToleranceLabel.Text = bonuses.TemperatureTolerance < 0.5f
            ? "нет"
            : $"+{bonuses.TemperatureTolerance:0} K";
        ToleranceLabel.FontColorOverride = bonuses.TemperatureTolerance > 0.5f ? GoodColor : MutedColor;

        StabilizationLabel.Text = FormatPercent(bonuses.StabilizationBonus);
        StabilizationLabel.FontColorOverride = bonuses.StabilizationBonus > 0.005f ? GoodColor : MutedColor;

        HeatGenLabel.Text = bonuses.HeatGenerationReduction < 0.005f
            ? "нет"
            : $"−{bonuses.HeatGenerationReduction:P0}";
        HeatGenLabel.FontColorOverride = bonuses.HeatGenerationReduction > 0.005f ? GoodColor : MutedColor;
    }

    private static string FormatPercent(float value)
    {
        return Math.Abs(value) < 0.005f ? "нет" : $"+{value:P0}";
    }

    private void UpdateReagents(CoolantMixerBoundUserInterfaceState state)
    {
        ReagentList.RemoveAllChildren();

        if (state.Reagents.Count == 0)
        {
            ReagentList.AddChild(new Label
            {
                Text = "пока пусто",
                FontColorOverride = MutedColor,
            });
            return;
        }

        foreach (var reagent in state.Reagents)
        {
            var name = _prototype.TryIndex(reagent.Reagent, out ReagentPrototype? proto)
                ? proto.LocalizedName
                : reagent.Reagent;

            var share = state.Volume > 0.01f ? reagent.Amount / state.Volume : 0f;

            ReagentList.AddChild(new Label
            {
                Text = $"{name} — {reagent.Amount:0} ед. ({share:P0})",
                ClipText = true,
            });
        }
    }

    private void UpdateSlot(
        SpriteView view,
        Label name,
        Label fill,
        NetEntity? item,
        FluidSlotState? slot,
        Button eject)
    {
        _entities.TryGetEntity(item, out var entity);

        view.SetEntity(entity);

        name.Text = entity is { } uid && _entities.TryGetComponent(uid, out MetaDataComponent? meta)
            ? meta.EntityName
            : "ячейка пуста";

        fill.Text = slot == null
            ? "—"
            : $"{slot.Volume:0} / {slot.MaxVolume:0} ед.";

        eject.Disabled = entity == null;
    }

    private static bool HasRoom(FluidSlotState? slot)
    {
        return slot is { } s && s.MaxVolume - s.Volume > 0.01f;
    }
}
