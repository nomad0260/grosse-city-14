using Content.Client.UserInterface.Controls;
using Content.Shared._Grosse.Ration;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Grosse.Ration;

[GenerateTypedNameReferences]
public sealed partial class RationTerminalWindow : FancyWindow
{
    public event Action<string, int>? OnQuotaChanged;
    public event Action<NetEntity>? OnIssueOne;
    public event Action? OnIssueAll;

    public RationTerminalWindow()
    {
        RobustXamlLoader.Load(this);
        IssueAllButton.OnPressed += _ => OnIssueAll?.Invoke();
    }

    public void UpdateEntries(RationTerminalBoundUserInterfaceState state)
    {
        Rows.RemoveAllChildren();
        EmptyLabel.Visible = state.Entries.Count == 0;

        foreach (var entry in state.Entries)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                Margin = new Thickness(0, 2),
            };

            row.AddChild(new Label
            {
                Text = entry.Name,
                HorizontalExpand = true,
                ClipText = true,
                MinWidth = 120,
            });
            row.AddChild(new Label
            {
                Text = entry.JobTitle,
                MinWidth = 160,
                ClipText = true,
            });

            var spin = new SpinBox { MinWidth = 90 };
            spin.IsValid = value => value >= 0 && value <= RationQuotaComponent.MaxCoupons;
            spin.OverrideValue(entry.Quota);
            var jobId = entry.JobId;
            spin.ValueChanged += args => OnQuotaChanged?.Invoke(jobId, args.Value);
            row.AddChild(spin);

            var issue = new Button
            {
                Text = Loc.GetString("ration-terminal-issue-one"),
                MinWidth = 140,
            };
            var body = entry.Body;
            issue.OnPressed += _ => OnIssueOne?.Invoke(body);
            row.AddChild(issue);

            Rows.AddChild(row);
        }
    }
}
