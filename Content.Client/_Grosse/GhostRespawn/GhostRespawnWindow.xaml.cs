using Content.Client.UserInterface.Controls;
using Content.Shared._Grosse.GhostRespawn;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Grosse.GhostRespawn;

[GenerateTypedNameReferences]
public sealed partial class GhostRespawnWindow : FancyWindow
{
    public event Action<NetEntity, string, int>? OnConfirm;

    private readonly Dictionary<int, (NetEntity Station, string JobId, bool Selectable)> _roles = new();
    private readonly Dictionary<int, int> _characters = new();
    private int? _selectedRole;
    private int _selectedCharacter = -1;

    public GhostRespawnWindow()
    {
        RobustXamlLoader.Load(this);
        ConfirmButton.OnPressed += _ => Confirm();
        CharacterSelect.OnItemSelected += args =>
        {
            CharacterSelect.SelectId(args.Id);
            _selectedCharacter = args.Id;
            UpdateConfirm();
        };
    }

    public void UpdateState(GhostRespawnEuiState state)
    {
        RoleList.RemoveAllChildren();
        _roles.Clear();
        _selectedRole = null;

        var index = 0;
        foreach (var role in state.Roles)
        {
            var id = index++;
            _roles[id] = (role.Station, role.JobId, role.Selectable);
            var button = new Button
            {
                Text = role.Name,
                Disabled = !role.Selectable,
                ToggleMode = true,
                HorizontalExpand = true,
            };
            var captured = id;
            button.OnPressed += _ => SelectRole(captured);
            RoleList.AddChild(button);
        }

        CharacterSelect.Clear();
        _characters.Clear();
        _selectedCharacter = -1;

        var charIndex = 0;
        foreach (var character in state.Characters)
        {
            var id = charIndex++;
            _characters[id] = character.Slot;
            CharacterSelect.AddItem(character.Name, id);
        }

        var hasCharacters = state.Characters.Count > 0;
        CharacterSelect.Visible = hasCharacters;
        NoCharactersLabel.Visible = !hasCharacters;
        if (hasCharacters)
        {
            CharacterSelect.SelectId(0);
            _selectedCharacter = 0;
        }

        UpdateConfirm();
    }

    private void SelectRole(int id)
    {
        if (!_roles.TryGetValue(id, out var role) || !role.Selectable)
            return;

        _selectedRole = id;
        var childIndex = 0;
        foreach (var child in RoleList.Children)
        {
            if (child is Button button)
                button.Pressed = childIndex == id;

            childIndex++;
        }

        UpdateConfirm();
    }

    private void UpdateConfirm()
    {
        var roleOk = _selectedRole is { } roleId &&
                     _roles.TryGetValue(roleId, out var role) &&
                     role.Selectable;
        var characterOk = _selectedCharacter >= 0 && _characters.ContainsKey(_selectedCharacter);
        ConfirmButton.Disabled = !roleOk || !characterOk;
    }

    private void Confirm()
    {
        if (ConfirmButton.Disabled)
            return;

        if (_selectedRole is not { } roleId || !_roles.TryGetValue(roleId, out var role) || !role.Selectable)
            return;

        if (!_characters.TryGetValue(_selectedCharacter, out var slot))
            return;

        ConfirmButton.Disabled = true;
        OnConfirm?.Invoke(role.Station, role.JobId, slot);
    }
}
