using System.Linq;
using System.Numerics;
using Content.Client.Pinpointer.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared._Grosse.CommanderTerminal;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Map;
using Robust.Shared.Utility;

namespace Content.Client._Grosse.CommanderTerminal;

[GenerateTypedNameReferences]
public sealed partial class CommanderTerminalWindow : FancyWindow
{
    private static readonly Color[] GroupColors =
    [
        new(60, 140, 255),
        new(255, 170, 50),
        new(70, 220, 130),
        new(220, 80, 220),
        new(255, 90, 90),
        new(80, 220, 220),
        new(230, 230, 80),
        new(170, 170, 170),
    ];

    private static readonly Color UnassignedColor = new(150, 150, 150);

    [Dependency] private IEntityManager _entities = default!;

    private readonly SharedTransformSystem _transform;
    private readonly SpriteSystem _sprites;

    private Texture? _blip;
    private Texture? _leaderBlip;

    private List<CommanderMember> _members = new();
    private List<CommanderGroup> _groups = new();
    private List<CommanderFloor> _floors = new();

    private string? _selectedGroupId;
    private string? _renameTarget;
    private NetEntity? _selectedGrid;
    private NetEntity? _shownGrid;
    private string? _floorSignature;
    private string? _crewSignature;
    private string? _orderSignature;
    private bool _suppressOrderSelect;
    private readonly Dictionary<string, Label> _crewLocations = new();
    private readonly Dictionary<string, string> _pendingAssign = new();
    private readonly Dictionary<string, CommanderMapEntry> _positions = new();

    public event Action<string>? OnCreateGroup;
    public event Action<string, string>? OnRenameGroup;
    public event Action<string>? OnDeleteGroup;
    public event Action<string, string>? OnAssign;
    public event Action<string>? OnRemove;
    public event Action<string, string>? OnSetLeader;
    public event Action<string, NetEntity, Vector2>? OnIssueOrder;

    public CommanderTerminalWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _transform = _entities.System<SharedTransformSystem>();
        _sprites = _entities.System<SpriteSystem>();

        Tabs.SetTabTitle(0, Loc.GetString("commander-terminal-tab-crew"));
        Tabs.SetTabTitle(1, Loc.GetString("commander-terminal-tab-map"));
        Tabs.SetTabTitle(2, Loc.GetString("commander-terminal-tab-groups"));

        CreateGroupButton.OnPressed += _ =>
        {
            OnCreateGroup?.Invoke(NewGroupName.Text);
            NewGroupName.Text = string.Empty;
        };

        RenameButton.OnPressed += _ =>
        {
            if (_selectedGroupId != null)
                OnRenameGroup?.Invoke(_selectedGroupId, RenameEdit.Text);
        };

        DeleteButton.OnPressed += _ =>
        {
            if (_selectedGroupId != null)
                OnDeleteGroup?.Invoke(_selectedGroupId);
        };

        OrderGroup.OnItemSelected += args =>
        {
            if (_suppressOrderSelect)
                return;

            OrderGroup.SelectId(args.Id);
            _selectedGroupId = OrderGroup.SelectedMetadata as string;
            _renameTarget = null;
            RefreshGroupList();
            RefreshGroupDetail();
            UpdateOrderHint();
        };

        NavMap.MapClickedAction += OnMapClicked;
    }

    public void ApplyMenu(CommanderTerminalState state)
    {
        _members = state.Members;
        _groups = state.Groups;
        _floors = state.Floors;
        StationLabel.Text = state.StationName;

        if (_selectedGroupId != null && _groups.All(group => group.GroupId != _selectedGroupId))
        {
            _selectedGroupId = null;
            _renameTarget = null;
        }

        EnsureFloor(state);
        RefreshCrew();
        RefreshOrderDropdown();
        RefreshFloors();
        ApplyFloor();
        RefreshGroupList();
        RefreshGroupDetail();
        UpdateOrderHint();
        ApplyStoredLocations();
    }

    public void ApplyMap(List<CommanderMapEntry> entries)
    {
        _positions.Clear();
        foreach (var entry in entries)
            _positions[entry.MemberId] = entry;

        ApplyStoredLocations();
        RefreshBlips();
    }

    private void OnMapClicked(MapCoordinates coordinates)
    {
        var group = SelectedGroup();
        if (group == null)
        {
            OrderHint.Text = Loc.GetString("commander-terminal-no-group");
            return;
        }

        if (group.LeaderId == null || _selectedGrid == null)
        {
            OrderHint.Text = Loc.GetString("commander-terminal-no-leader");
            return;
        }

        OnIssueOrder?.Invoke(group.GroupId, _selectedGrid.Value, coordinates.Position);
    }

    private void EnsureFloor(CommanderTerminalState state)
    {
        if (_selectedGrid != null && _floors.Any(floor => floor.Grid == _selectedGrid))
            return;

        var consoleFloor = _floors.FirstOrDefault(floor => floor.Grid == state.ConsoleGrid);
        _selectedGrid = consoleFloor?.Grid ?? _floors.FirstOrDefault()?.Grid;
        _shownGrid = null;
    }

    private void RefreshFloors()
    {
        var signature = string.Join(",", _floors.Select(floor => floor.Grid.ToString()));
        if (signature != _floorSignature)
        {
            _floorSignature = signature;
            FloorBar.DisposeAllChildren();

            foreach (var floor in _floors)
            {
                var grid = floor.Grid;
                var button = new Button
                {
                    Text = Loc.GetString("commander-terminal-floor", ("depth", floor.Depth)),
                    Margin = new Thickness(0, 0, 4, 0),
                };
                button.OnPressed += _ =>
                {
                    _selectedGrid = grid;
                    _shownGrid = null;
                    RefreshFloors();
                    ApplyFloor();
                };
                FloorBar.AddChild(button);
            }
        }

        var index = 0;
        foreach (var floor in _floors)
        {
            if (index < FloorBar.ChildCount && FloorBar.GetChild(index) is Button button)
                button.Modulate = floor.Grid == _selectedGrid ? Color.LightBlue : Color.White;

            index++;
        }
    }

    private void ApplyFloor()
    {
        if (_selectedGrid == null)
        {
            NavMap.Visible = false;
            RefreshBlips();
            return;
        }

        NavMap.Visible = true;
        if (_shownGrid != _selectedGrid)
        {
            _shownGrid = _selectedGrid;
            NavMap.MapUid = _entities.GetEntity(_selectedGrid.Value);
            NavMap.ForceNavMapUpdate();
        }

        RefreshBlips();
    }

    private void RefreshBlips()
    {
        NavMap.TrackedEntities.Clear();

        if (NavMap.MapUid == null || !_entities.TryGetComponent<TransformComponent>(NavMap.MapUid.Value, out var gridXform))
            return;

        _blip ??= _sprites.Frame0(new SpriteSpecifier.Texture(new ResPath("/Textures/Interface/NavMap/beveled_circle.png")));
        _leaderBlip ??= _sprites.Frame0(new SpriteSpecifier.Texture(new ResPath("/Textures/Interface/NavMap/beveled_star.png")));

        foreach (var member in _members)
        {
            if (!_positions.TryGetValue(member.MemberId, out var position))
                continue;

            var coordinates = _entities.GetCoordinates(position.Coordinates);
            if (_transform.ToMapCoordinates(coordinates).MapId != gridXform.MapID)
                continue;

            var group = _groups.FirstOrDefault(candidate => candidate.GroupId == member.GroupId);
            var color = group == null ? UnassignedColor : GroupColor(group.ColorIndex);
            NavMap.TrackedEntities[member.Body] = new NavMapBlip(
                coordinates,
                member.IsLeader ? _leaderBlip : _blip,
                color,
                blinks: false,
                selectable: false,
                scale: member.IsLeader ? 1.45f : 1f);
        }
    }

    private void RefreshCrew()
    {
        var signature = CrewSignature();
        if (signature == _crewSignature)
            return;

        _crewSignature = signature;
        _crewLocations.Clear();
        CrewList.DisposeAllChildren();
        CrewEmpty.Visible = _members.Count == 0;

        foreach (var member in _members)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(0, 2),
            };

            var group = _groups.FirstOrDefault(candidate => candidate.GroupId == member.GroupId);
            row.AddChild(new Label
            {
                Text = member.IsLeader ? $"{member.Name} ★" : member.Name,
                MinWidth = 180,
                ClipText = true,
            });
            row.AddChild(new Label
            {
                Text = member.IdName,
                MinWidth = 180,
                ClipText = true,
            });
            var locationLabel = new Label
            {
                Text = _positions.TryGetValue(member.MemberId, out var position) ? position.Location : string.Empty,
                MinWidth = 140,
                ClipText = true,
            };
            _crewLocations[member.MemberId] = locationLabel;
            row.AddChild(locationLabel);
            row.AddChild(new Label
            {
                Text = group?.Name ?? Loc.GetString("commander-terminal-unassigned"),
                MinWidth = 120,
                ClipText = true,
                FontColorOverride = group == null ? UnassignedColor : GroupColor(group.ColorIndex),
            });

            var options = new OptionButton { MinWidth = 160 };
            options.AddItem(Loc.GetString("commander-terminal-pick-group"), 0);
            var optionId = 1;
            foreach (var candidate in _groups)
            {
                options.AddItem(candidate.Name, optionId);
                options.SetItemMetadata(options.GetIdx(optionId), candidate.GroupId);
                optionId++;
            }

            var memberId = member.MemberId;
            if (_pendingAssign.TryGetValue(memberId, out var pending) && pending == member.GroupId)
                _pendingAssign.Remove(memberId);

            var selectedGroup = _pendingAssign.GetValueOrDefault(memberId) ?? member.GroupId;
            if (selectedGroup != null)
            {
                for (var i = 0; i < options.ItemCount; i++)
                {
                    if (options.GetItemMetadata(i) as string == selectedGroup)
                    {
                        options.Select(i);
                        break;
                    }
                }
            }

            options.OnItemSelected += args =>
            {
                options.SelectId(args.Id);
                if (options.SelectedMetadata is string picked)
                    _pendingAssign[memberId] = picked;
                else
                    _pendingAssign.Remove(memberId);
            };

            var assign = new Button { Text = Loc.GetString("commander-terminal-assign") };
            assign.OnPressed += _ =>
            {
                if (options.SelectedMetadata is not string groupId)
                    return;

                _pendingAssign[memberId] = groupId;
                OnAssign?.Invoke(groupId, memberId);
            };

            var remove = new Button
            {
                Text = Loc.GetString("commander-terminal-remove"),
                Disabled = member.GroupId == null,
            };
            remove.OnPressed += _ => OnRemove?.Invoke(memberId);

            row.AddChild(options);
            row.AddChild(assign);
            row.AddChild(remove);
            CrewList.AddChild(row);
        }
    }

    private void ApplyStoredLocations()
    {
        foreach (var (memberId, label) in _crewLocations)
        {
            if (_positions.TryGetValue(memberId, out var position))
                label.Text = position.Location;
        }
    }

    private string CrewSignature()
    {
        var members = string.Join("|", _members.Select(member =>
            $"{member.MemberId}:{member.Name}:{member.IdName}:{member.GroupId}:{member.IsLeader}"));
        var groups = string.Join("|", _groups.Select(group => $"{group.GroupId}:{group.Name}"));
        return members + "#" + groups;
    }

    private void RefreshOrderDropdown()
    {
        var signature = string.Join("|", _groups.Select(group => $"{group.GroupId}:{group.Name}")) + "#" + _selectedGroupId;
        if (signature == _orderSignature)
            return;

        _orderSignature = signature;
        _suppressOrderSelect = true;
        OrderGroup.Clear();
        OrderGroup.AddItem(Loc.GetString("commander-terminal-no-group-selected"), 0);

        var optionId = 1;
        var selected = 0;
        foreach (var group in _groups)
        {
            OrderGroup.AddItem(group.Name, optionId);
            OrderGroup.SetItemMetadata(OrderGroup.GetIdx(optionId), group.GroupId);
            if (group.GroupId == _selectedGroupId)
                selected = optionId;
            optionId++;
        }

        OrderGroup.SelectId(selected);
        _suppressOrderSelect = false;
    }

    private void RefreshGroupList()
    {
        GroupList.DisposeAllChildren();

        foreach (var group in _groups)
        {
            var groupId = group.GroupId;
            var button = new Button
            {
                Text = Loc.GetString("commander-terminal-group-entry", ("name", group.Name), ("count", group.Members.Count)),
                Modulate = group.GroupId == _selectedGroupId ? GroupColor(group.ColorIndex) : Color.White,
            };
            button.OnPressed += _ =>
            {
                _selectedGroupId = groupId;
                _renameTarget = null;
                RefreshOrderDropdown();
                RefreshGroupList();
                RefreshGroupDetail();
                UpdateOrderHint();
            };
            GroupList.AddChild(button);
        }
    }

    private void RefreshGroupDetail()
    {
        var group = SelectedGroup();
        GroupDetailEmpty.Visible = group == null;
        GroupDetailBody.Visible = group != null;
        if (group == null)
            return;

        if (_renameTarget != group.GroupId)
        {
            _renameTarget = group.GroupId;
            RenameEdit.Text = group.Name;
        }

        var leader = _members.FirstOrDefault(member => member.MemberId == group.LeaderId);
        LeaderLabel.Text = leader == null
            ? Loc.GetString("commander-terminal-no-leader-name")
            : Loc.GetString("commander-terminal-leader", ("name", leader.Name));

        MemberList.DisposeAllChildren();
        foreach (var memberId in group.Members)
        {
            var member = _members.FirstOrDefault(candidate => candidate.MemberId == memberId);
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(0, 2),
            };
            row.AddChild(new Label
            {
                Text = member == null
                    ? Loc.GetString("commander-terminal-missing-member")
                    : member.IsLeader ? $"{member.Name} ★" : member.Name,
                HorizontalExpand = true,
            });

            var id = memberId;
            var leaderButton = new Button
            {
                Text = Loc.GetString("commander-terminal-set-leader"),
                Disabled = member == null || member.IsLeader,
            };
            leaderButton.OnPressed += _ => OnSetLeader?.Invoke(group.GroupId, id);
            row.AddChild(leaderButton);
            MemberList.AddChild(row);
        }
    }

    private void UpdateOrderHint()
    {
        var group = SelectedGroup();
        if (group == null)
        {
            OrderHint.Text = Loc.GetString("commander-terminal-order-hint-empty");
            return;
        }

        if (group.LeaderId == null)
        {
            OrderHint.Text = Loc.GetString("commander-terminal-no-leader");
            return;
        }

        OrderHint.Text = Loc.GetString("commander-terminal-order-hint", ("group", group.Name));
    }

    private CommanderGroup? SelectedGroup()
    {
        return _groups.FirstOrDefault(group => group.GroupId == _selectedGroupId);
    }

    private static Color GroupColor(int index)
    {
        return GroupColors[Math.Abs(index) % GroupColors.Length];
    }
}
