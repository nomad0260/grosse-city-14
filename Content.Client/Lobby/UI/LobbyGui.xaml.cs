using Content.Client.UserInterface.Systems.EscapeMenu;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;
using Robust.Shared.Timing;

namespace Content.Client.Lobby.UI
{
    [GenerateTypedNameReferences]
    public sealed partial class LobbyGui : UIScreen
    {
        [Dependency] private IClientConsoleHost _consoleHost = default!;

        // Ширина панелей считается от ширины окна, а не задаётся жёстко:
        // так лобби остаётся читаемым и на 1280×720, и на ультрашироких мониторах.
        private const float WideBreakpoint = 1180f;
        private const float NarrowBreakpoint = 980f;
        private const float TinyBreakpoint = 840f;

        private const float MinLeftWidth = 200f;
        private const float MaxLeftWidth = 360f;
        private const float MinRightWidth = 240f;
        private const float MaxRightWidth = 420f;

        private const float BackgroundInterval = 40f;
        private const float BackgroundFadeTime = 1.8f;

        private static readonly string[] LobbyBackgrounds =
        {
            "/Textures/_Grosse/hl2_city17.png",
            "/Textures/_Grosse/hl2_lobby_dusk.png",
            "/Textures/_Grosse/hl2_lobby_rain.png",
            "/Textures/_Grosse/hl2_lobby_combine.png",
        };

        private LobbyGuiState _state = LobbyGuiState.Default;
        private int _backgroundIndex;
        private float _backgroundTimer;
        private float _backgroundFade = -1f;

        public LobbyGui()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);

            SetAnchorPreset(MainContainer, LayoutPreset.Wide);
            SetAnchorPreset(Background, LayoutPreset.Wide);
            SetAnchorPreset(Scrim, LayoutPreset.Wide);

            LeaveButton.OnPressed += _ => _consoleHost.ExecuteCommand("disconnect");
            OptionsButton.OnPressed += _ => UserInterfaceManager.GetUIController<OptionsUIController>().ToggleWindow();

            _backgroundIndex = Random.Shared.Next(LobbyBackgrounds.Length);
            Background.TexturePath = LobbyBackgrounds[_backgroundIndex];
            BackgroundNext.Visible = false;

            OnResized += UpdateResponsiveLayout;
            UpdateResponsiveLayout();
        }

        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);

            if (_backgroundFade < 0f)
            {
                _backgroundTimer += args.DeltaSeconds;
                if (_backgroundTimer < BackgroundInterval)
                    return;

                _backgroundTimer = 0f;
                _backgroundIndex = (_backgroundIndex + 1) % LobbyBackgrounds.Length;
                BackgroundNext.TexturePath = LobbyBackgrounds[_backgroundIndex];
                BackgroundNext.Modulate = Color.White.WithAlpha(0f);
                BackgroundNext.Visible = true;
                _backgroundFade = 0f;
                return;
            }

            _backgroundFade = Math.Min(1f, _backgroundFade + args.DeltaSeconds / BackgroundFadeTime);
            var alpha = Easings.InOutQuad(_backgroundFade);
            BackgroundNext.Modulate = Color.White.WithAlpha(alpha);
            Background.Modulate = Color.White.WithAlpha(1f - alpha);

            if (_backgroundFade < 1f)
                return;

            Background.TexturePath = LobbyBackgrounds[_backgroundIndex];
            Background.Modulate = Color.White;
            BackgroundNext.Visible = false;
            BackgroundNext.Modulate = Color.White.WithAlpha(0f);
            _backgroundFade = -1f;
        }

        public void SwitchState(LobbyGuiState state)
        {
            _state = state;

            DefaultState.Visible = false;
            CharacterSetupState.Visible = false;

            switch (state)
            {
                case LobbyGuiState.Default:
                    DefaultState.Visible = true;
                    break;
                case LobbyGuiState.CharacterSetup:
                    CharacterSetupState.Visible = true;
                    UserInterfaceManager.GetUIController<LobbyUIController>().ReloadCharacterSetup();
                    break;
            }

            UpdateResponsiveLayout();
        }

        /// <summary>
        /// Раскладывает лобби под текущее разрешение: панели занимают фиксированную
        /// долю ширины, но не разрастаются бесконечно и всегда оставляют центр экрана.
        /// </summary>
        private void UpdateResponsiveLayout()
        {
            var width = Size.X;
            if (width <= 0f)
                return;

            var tiny = width < TinyBreakpoint;
            var narrow = width < NarrowBreakpoint;
            var compact = width < WideBreakpoint;

            var shortViewport = Size.Y > 0f && Size.Y < 620f;

            var margin = tiny ? 8f : narrow ? 10f : compact ? 12f : 18f;
            var gap = tiny ? 6 : narrow ? 8 : compact ? 12 : 18;

            MainContainer.Margin = new Thickness(margin);
            MainContainer.SeparationOverride = gap;

            // На низких окнах описание сервера прокручивается, а не выдавливает чат и ссылки.
            InfoScroll.MaxHeight = shortViewport ? 165f : 240f;
            Chat.MinHeight = shortViewport ? 64f : 110f;

            // В редакторе персонажа левая панель только мешает: отдаём ему всю ширину.
            if (_state == LobbyGuiState.CharacterSetup)
            {
                LeftSide.Visible = false;

                var available = width - margin * 2f;
                RightSide.SetWidth = Math.Min(available, RightSide.MaxWidth);

                UpdateCompactControls(LeftSide.SetWidth, RightSide.SetWidth);
                return;
            }

            LeftSide.Visible = true;

            var left = Math.Clamp(width * (tiny ? 0.30f : narrow ? 0.33f : 0.27f),
                tiny ? 200f : narrow ? 300f : 340f, MaxLeftWidth);
            var right = Math.Clamp(width * (tiny || narrow ? 0.35f : 0.29f),
                tiny ? 240f : narrow ? 290f : 310f, MaxRightWidth);

            var availableWidth = width - margin * 2f - gap;
            var centerMin = Math.Max(tiny ? 180f : narrow ? 210f : 240f,
                width * (tiny ? 0.24f : narrow ? 0.26f : 0.32f));
            var maxSideWidth = Math.Max(0f, availableWidth - centerMin);

            var total = left + right;
            if (total > maxSideWidth && total > 0f)
            {
                var scale = maxSideWidth / total;
                left *= scale;
                right *= scale;
            }

            // Совсем узкие окна: лучше отдать центру остаток, чем сжать панели в нечитаемое.
            left = Math.Max(left, MinLeftWidth);
            right = Math.Max(right, MinRightWidth);

            LeftSide.SetWidth = left;
            RightSide.SetWidth = right;

            UpdateCompactControls(left, right);
        }

        private void UpdateCompactControls(float leftWidth, float rightWidth)
        {
            // На совсем узком экране описание сервера и ссылки только съедают место у чата.
            var showExtras = Size.X >= 700f;
            InfoScroll.Visible = showExtras;
            ServerInfo.Visible = showExtras;
            LinkBanner.Visible = showExtras;

            var linkColumns = leftWidth < 250f ? 1 : leftWidth < 290f ? 2 : 3;
            LinkBanner.SetCompact(linkColumns);
            PvpLoadout.SetCompact(rightWidth < 280f);
        }

        public enum LobbyGuiState : byte
        {
            /// <summary>
            ///  The default state, i.e., what's seen on launch.
            /// </summary>
            Default,

            /// <summary>
            ///  The character setup state.
            /// </summary>
            CharacterSetup
        }
    }
}
