    /// <summary>
    /// Shows the real engine version, build id and server name in the node
    /// status block.
    /// </summary>
    private void ApplyBuildInfo()
    {
        // Content assemblies run inside the Robust sandbox: System.IO and
        // Assembly.Location are not allowed there, so build info can only come
        // from the CVars the launcher passes in. A raw dev run uses defaults.
        var engineVersion = _cfg.GetCVar(Robust.Shared.CVars.BuildEngineVersion);
        if (string.IsNullOrWhiteSpace(engineVersion))
            engineVersion = typeof(Robust.Shared.CVars).Assembly.GetName().Version?.ToString(3);

        EngineVersionLabel.Text = $"SS14 v{engineVersion ?? "—"}";

        var build = _cfg.GetCVar(Robust.Shared.CVars.BuildHash);
        if (string.IsNullOrWhiteSpace(build))
            build = _cfg.GetCVar(Robust.Shared.CVars.BuildVersion);

        var buildShort = string.IsNullOrWhiteSpace(build)
            ? "—"
            : (build.Length > 7 ? build[..7] : build);

        BuildDateLabel.Text = Loc.GetString("ui-lobby-build-line", ("build", buildShort));

        ChatHint.Text = Loc.GetString("ui-lobby-chat-hint", ("key",
            BoundKeyHelper.IsBound(ContentKeyFunctions.FocusChat)
                ? BoundKeyHelper.ShortKeyName(ContentKeyFunctions.FocusChat)
                : "Tab"));
    }

