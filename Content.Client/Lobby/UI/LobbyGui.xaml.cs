    /// <summary>
    /// Resolves the node caption from the actual connection instead of a
    /// hardcoded "OPERATIONAL" string.
    /// </summary>
    public void UpdateNodeStatus(bool connected, int ping, bool lateJoinOpen)
    {
        if (!connected)
        {
            SetNodeStatus(Loc.GetString("ui-lobby-node-offline"), Color.FromHex("#9E3937"), 0.08f);
            return;
        }

        if (lateJoinOpen)
        {
            SetNodeStatus(Loc.GetString("ui-lobby-node-latejoin"), Color.FromHex("#63C77B"), 0.85f);
            return;
        }

        if (ping > 180)
        {
            SetNodeStatus(Loc.GetString("ui-lobby-node-degraded"), Color.FromHex("#C2A16A"), Math.Clamp(1f - ping / 400f, 0.25f, 0.6f));
            return;
        }

        SetNodeStatus(Loc.GetString("ui-lobby-node-operational"), Color.FromHex("#63C77B"), 0.9f);
    }

    /// <summary>
    /// Cycles the reference overlay: off, 50%, 100%. Used by the lobbyref
    /// console command to compare the live layout with the design.
    /// </summary>
    public int CycleReferenceOverlay()
    {
        _referenceStage = (_referenceStage + 1) % 3;
        // Load the comparison still only when the dev command is used; shipping
        // it in the XAML would keep a 1600x900 texture resident for everyone.
        ReferenceOverlay.Texture ??= _resourceCache.GetTexture("/Textures/_Grosse/lobby_reference.png");
        ReferenceOverlay.Visible = _referenceStage > 0;
        ReferenceOverlay.Modulate = Color.White.WithAlpha(_referenceStage * 0.5f);
        return _referenceStage;
    }

    private static string FormatCountdown(float seconds)
    {
        var total = (int) MathF.Ceiling(Math.Clamp(seconds, 0f, 3599f));
        return $"{total / 60:D2}:{total % 60:D2}";
    }

    private void ConfirmTerminate()
    {
        if (_leaveConfirmTimer > 0f)
        {
            _consoleHost.ExecuteCommand("disconnect");
            return;
        }

        _leaveConfirmTimer = ConfirmSeconds;
        LeaveLabel.Text = Loc.GetString("ui-lobby-menu-confirm");
    }

    private static void TickConfirm(ref float timer, Label label, string idleText, float delta)
    {
        if (timer <= 0f)
            return;

        timer -= delta;
        if (timer > 0f)
            return;

        timer = 0f;
        label.Text = idleText;
    }

    private void SetChatForcedOpen(bool open)
    {
        _chatForcedOpen = open;
        if (open)
            _unreadCount = 0;

        UpdateResponsiveLayout();
    }

    private void HookChatEvents()
    {
        if (_chatEventsHooked)
            return;

        _chatController = UserInterfaceManager.GetUIController<ChatUIController>();
        _chatController.MessageAdded += OnChatMessageAdded;
        _chatEventsHooked = true;
        UpdateChatStrip();
    }

    private void UnhookChatEvents()
    {
        if (!_chatEventsHooked || _chatController == null)
            return;

        _chatController.MessageAdded -= OnChatMessageAdded;
        _chatEventsHooked = false;
    }

    private void OnChatMessageAdded(ChatMessage message)
    {
        // The collapsed strip counts every message that arrives while the chat
        // is hidden; expanding it clears the badge.
        if (_state != LobbyGuiState.Default || _chatForcedOpen || Size.X >= 1180f)
            return;

        _unreadCount++;
        UpdateChatStrip();
    }

    private void UpdateChatStrip()
    {
        ChatStripUnread.Text = _unreadCount > 99 ? "99+" : _unreadCount > 0 ? _unreadCount.ToString() : string.Empty;
        ChatStripUnread.Visible = _unreadCount > 0 && !_chatForcedOpen;
        ChatStripLabel.Text = _chatForcedOpen ? "CLOSE" : "CHAT";
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        HookChatEvents();
        UpdateChatStrip();
        ApplyChatFocusStyle(Chat.ChatInput.Input.HasKeyboardFocus());
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        UnhookChatEvents();
    }

    private static void AnchorFull(Control control)
    {
        LayoutContainer.SetAnchorPreset(control, LayoutContainer.LayoutPreset.Wide);
