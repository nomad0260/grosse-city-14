    public LobbyGui()
    {
        LobbyFx.Initialize();

        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        LayoutBackground();
        PlaceLobbyControls();
        StyleLobbyChat();
        ApplyBuildInfo();
        HookChatEvents();

        // Frosted Graphite blur behind side columns and chat so text never clashes with bright scene details.
        LeftSide.Backdrop = Background;
        RightSide.Backdrop = Background;
        LeftSide.Tint = Color.FromHex("#151817").WithAlpha(0.32f);
        LeftSide.EdgeColor = Color.Transparent;
        LeftSide.ShowLeftRail = true;
        RightSide.Tint = Color.FromHex("#151817").WithAlpha(0.24f);
        RightSide.EdgeColor = Color.Transparent;
        ChatGlass.Backdrop = Background;
        ChatGlass.Tint = Color.Transparent;
        ChatGlass.EdgeColor = Color.Transparent;
        ChatGlass.ShowChatFrame = true;

        // Bottom-bar controls are inline terminal links in the reference, not boxes.
        AHelpButton.StyleBoxOverride = new StyleBoxFlat(Color.Transparent);
        ObserveButton.StyleBoxOverride = new StyleBoxFlat(Color.Transparent);

        // Выход из лобби требует второго подтверждения: первый клик
        // только взводит действие на несколько секунд.
        LeaveButton.OnPressed += _ => ConfirmTerminate();
        ChatStrip.OnPressed += _ => SetChatForcedOpen(!_chatForcedOpen);

        // Плашка подтверждения читается как состояние готовности.
        ReadyButton.OnToggled += args => SetReadyPressed(args.Pressed);
        OptionsButton.OnPressed += _ => UserInterfaceManager.GetUIController<OptionsUIController>().ToggleWindow();
        MenuButton.OnPressed += _ => UserInterfaceManager.GetUIController<EscapeUIController>().ToggleWindow();
        TopGuideButton.OnPressed += _ => UserInterfaceManager.GetUIController<GuidebookUIController>().ToggleGuidebook();
        TutorialButton.OnPressed += _ => Tutorial.Open();
        TopUpdatesButton.OnPressed += _ => UserInterfaceManager.GetUIController<ChangelogUIController>().ToggleWindow();

        PvpLoadout.SetCompact(true);

        if (!Background.SetFrameSequenceBackground(LobbyFramesFolder))
            Background.SetAnimatedBackground(LobbyRsiPath, LobbyRsiState);

        StartIntro();

        OnResized += UpdateResponsiveLayout;
        UpdateResponsiveLayout();
        UpdateTopBar();

        // Бриффинг показывается при каждом заходе в лобби. Отключается кнопкой
        // «больше не показывать», вернуть его можно кнопкой Tutorial в подсказках.
        if (!_cfg.GetCVar(GrosseCVars.LobbyTutorialDisabled))
            Tutorial.Open();
    }

