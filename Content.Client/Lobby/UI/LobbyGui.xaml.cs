    private static void Anchor(Control control, LayoutContainer.LayoutPreset preset, float x = 0f, float y = 0f)
    {
        LayoutContainer.SetAnchorPreset(control, preset);
        LayoutContainer.SetMarginsPreset(control, preset, LayoutContainer.LayoutPresetMode.MinSize);

        switch (preset)
        {
            case LayoutContainer.LayoutPreset.TopLeft:
                LayoutContainer.SetMarginLeft(control, x);
                LayoutContainer.SetMarginTop(control, y);
                break;
            case LayoutContainer.LayoutPreset.TopRight:
                LayoutContainer.SetMarginRight(control, -x);
                LayoutContainer.SetMarginTop(control, y);
                break;
            case LayoutContainer.LayoutPreset.BottomLeft:
                LayoutContainer.SetMarginLeft(control, x);
                LayoutContainer.SetMarginBottom(control, -y);
                break;
            case LayoutContainer.LayoutPreset.BottomRight:
                LayoutContainer.SetMarginRight(control, -x);
                LayoutContainer.SetMarginBottom(control, -y);
                break;
        }
    }

    /// <summary>
    /// Центрирует всю композицию по горизонтали и растягивает боковые
    /// колонки на всю высоту окна независимо от разрешения. Внутренние блоки
    /// распределяются гибкими зазорами, поэтому макет не расползается и не
    /// оставляет пустых полос при смене высоты экрана.
    /// </summary>
    private void UpdateResponsiveLayout()
    {
        var width = Size.X;
        var height = Size.Y;
        if (width <= 0f || height <= 0f)
            return;

        _bottomMargin = Math.Clamp(height * 0.036f, 20f, 36f);

        // Сетка референса: шапка и левая колонка выровнены по одной вертикальной координатной линии (railX),
        // досье стоит отдельной карточкой у правого края.
        var railX = Math.Clamp(width * 0.12f, 110f, 205f);
        _leftMargin = railX - 40f;
        _rightMargin = Math.Clamp(width * 0.025f, 14f, 44f);
        var headerLeft = MathF.Max(12f, railX - 81f);
        var leftWidth = Math.Clamp(width * 0.22f, 330f, 400f);
        var rightWidth = Math.Clamp(width * 0.195f, 300f, 360f);

        LeftSide.SetWidth = leftWidth;
        RightSide.SetWidth = rightWidth;

        // Левая колонка начинается сразу под вертикальной линией шапки, образуя единую направляющую.
        var top = Math.Clamp(height * 0.16f, 118f, 165f);
        var columnBottom = _bottomMargin + Math.Clamp(height * 0.085f, 50f, 84f);

        LayoutContainer.SetMarginLeft(LeftSide, _leftMargin);
        LayoutContainer.SetMarginTop(LeftSide, top);
        LayoutContainer.SetMarginBottom(LeftSide, -columnBottom);

        LayoutContainer.SetMarginRight(RightSide, -_rightMargin);
        LayoutContainer.SetMarginTop(RightSide, Math.Clamp(height * 0.083f, 62f, 92f));

        LayoutContainer.SetMarginLeft(TopBar, headerLeft);
        LayoutContainer.SetMarginRight(TopBar, -_rightMargin);

        LayoutContainer.SetMarginLeft(TopLeftPanel, headerLeft);
        LayoutContainer.SetMarginBottom(TopLeftPanel, -_bottomMargin);
        LayoutContainer.SetMarginRight(BottomRight, -_rightMargin);
        LayoutContainer.SetMarginBottom(BottomRight, -_bottomMargin);

        // Чат размещён в правом нижнем углу (под карточкой досье), с отступом
        // под нижнюю строку подсказки и срезанными углами как на референсе.
        var chatHeight = Math.Clamp(height * 0.165f, 128f, 168f);
        var chatBottom = _bottomMargin + 26f;
        var chatRight = _rightMargin;
        var chatWidth = Math.Clamp(width * 0.35f, 340f, 520f);
        var chatLeft = width - chatRight - chatWidth;
        var columnRight = _leftMargin + leftWidth + 28f;
        var wideChat = width >= 1180f;

        if (!wideChat)
        {
            // Полоса садится над нижней строкой подсказок, чат раскрывается над ней.
            const float stripHeight = 32f;
            var stripWidth = Math.Clamp(width * 0.3f, 200f, 300f);
            var stripLeft = width - stripWidth - _rightMargin;
            SetChatBounds(ChatStrip, stripLeft, _bottomMargin + 36f, stripWidth, stripHeight);
            SetChatBounds(ChatGlass, _leftMargin, _bottomMargin + stripHeight + 44f,
                MathF.Max(300f, width - _leftMargin - _rightMargin), chatHeight);
            SetChatBounds(Chat, _leftMargin + 10f, _bottomMargin + stripHeight + 46f,
                MathF.Max(284f, width - _leftMargin - _rightMargin - 16f), chatHeight - 6f);
        }
        else
        {
            if (chatLeft < columnRight)
            {
                chatLeft = columnRight;
                chatWidth = MathF.Max(320f, width - chatRight - chatLeft);
            }

            SetChatBounds(ChatGlass, chatLeft, chatBottom, chatWidth, chatHeight);
            SetChatBounds(Chat, chatLeft + 10f, chatBottom + 2f, chatWidth - 16f, chatHeight - 6f);
        }

        if (wideChat)
        {
            _chatForcedOpen = false;
            _unreadCount = 0;
        }

        ChatStrip.Visible = _state == LobbyGuiState.Default && !wideChat;
        ChatGlass.Visible = _state == LobbyGuiState.Default && (wideChat || _chatForcedOpen);
        Chat.Visible = ChatGlass.Visible;
        UpdateChatStrip();

        // Голосования встают над чатом, чтобы не перекрывать ни его, ни меню.
        if (!wideChat)
        {
            VoteContainer.MaxWidth = MathF.Max(240f, MathF.Min(360f, width - _leftMargin - _rightMargin));
            LayoutContainer.SetMarginLeft(VoteContainer, _leftMargin);
            LayoutContainer.SetMarginBottom(VoteContainer, -(_bottomMargin + 32f + 44f + chatHeight + 12f));
        }
        else
        {
            VoteContainer.MaxWidth = MathF.Max(240f, MathF.Min(360f, chatWidth));
            LayoutContainer.SetMarginLeft(VoteContainer, chatLeft);
            LayoutContainer.SetMarginBottom(VoteContainer, -(chatBottom + chatHeight + 12f));
        }

        // На 720p левая колонка должна уместиться между шапкой и нижней строкой.
        var compact = height < 820f;
        DeployMenuRow.MinHeight = compact ? 44f : 58f;
        CharacterSetupButton.MinHeight = compact ? 38f : 54f;
        TopUpdatesButton.MinHeight = compact ? 38f : 54f;
        OptionsButton.MinHeight = compact ? 38f : 54f;
        LeaveButton.MinHeight = compact ? 38f : 54f;
        ReadyButton.MinHeight = compact ? 58f : 66f;
        MenuTop.MinHeight = compact ? 12f : 18f;
        MenuGap.MinHeight = compact ? 12f : 60f;
        NodeGap.MinHeight = compact ? 6f : 12f;
        ActionGap.MinHeight = compact ? 10f : 20f;

        // На низких экранах карточка режима тоже должна ужиматься, иначе
        // раскрытый список классов вместе с досье выходит за нижний край.
        PvpLoadout.SetCompact(width < 1400f || height < 820f);
    }

    private void TickLobbyTimers(float delta)
    {
        if (_noticeTimer > 0f)
        {
            _noticeTimer -= delta;
            if (_noticeTimer <= 0f)
            {
                _noticeTimer = 0f;
                DeployStatus.FontColorOverride = null;
                RefreshDeployStatus();
            }
        }

        TickConfirm(ref _leaveConfirmTimer, LeaveLabel, Loc.GetString("ui-lobby-menu-terminate"), delta);
    }

    private static void SetChatBounds(Control control, float left, float bottom, float width, float height)
    {
        LayoutContainer.SetMarginLeft(control, left);
        LayoutContainer.SetMarginBottom(control, -bottom);
        control.SetWidth = width;
        control.SetHeight = height;
    }

    /// <summary>
    /// Каскадный вход: панели проявляются по очереди и слегка подъезжают к
    /// своим местам, чтобы экран читался как включение терминала.
    /// </summary>
    private void StartIntro()
    {
        if (LobbyFx.ReducedMotion)
        {
            ApplyIntro(1f);
            return;
        }

        _introTime = 0f;
        ApplyIntro(0f);
    }

    private void ApplyIntro(float t)
    {
        SetIntroAlpha(TopBar, Ease(t, 0f, 0.3f));
        SetIntroAlpha(LeftSide, Ease(t, 0.05f, 0.45f));
        SetIntroAlpha(RightSide, Ease(t, 0.1f, 0.5f));
        SetIntroAlpha(ChatGlass, Ease(t, 0.16f, 0.58f));
        SetIntroAlpha(Chat, Ease(t, 0.16f, 0.58f));
        SetIntroAlpha(BottomRight, Ease(t, 0.18f, 0.58f));
        SetIntroAlpha(TopLeftPanel, Ease(t, 0.24f, 0.62f));

        var left = 1f - Ease(t, 0.05f, 0.55f);
        var right = 1f - Ease(t, 0.1f, 0.6f);
        var bottomRight = 1f - Ease(t, 0.18f, 0.65f);
        var bottomLeft = 1f - Ease(t, 0.24f, 0.68f);

        LayoutContainer.SetMarginLeft(LeftSide, _leftMargin - 18f * left);
        LayoutContainer.SetMarginRight(RightSide, -_rightMargin + 18f * right);
        LayoutContainer.SetMarginBottom(BottomRight, -_bottomMargin + 14f * bottomRight);
        LayoutContainer.SetMarginBottom(TopLeftPanel, -_bottomMargin + 14f * bottomLeft);
    }

    private static float Ease(float t, float start, float end)
    {
        var progress = Math.Clamp((t - start) / (end - start), 0f, 1f);
        return Easings.InOutQuad(progress);
    }

    private static void SetIntroAlpha(Control control, float alpha)
    {
        control.Modulate = Color.White.WithAlpha(alpha);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        _time += args.DeltaSeconds;
        TickLobbyTimers(args.DeltaSeconds);

        _topBarTimer += args.DeltaSeconds;
        if (_topBarTimer >= TopBarUpdateInterval)
        {
            _topBarTimer = 0f;
            UpdateTopBar();
        }

        if (_introTime >= 0f)
        {
            _introTime += args.DeltaSeconds;
            var progress = Math.Clamp(_introTime / IntroDuration, 0f, 1f);
            ApplyIntro(progress);

            if (progress >= 1f)
            {
                _introTime = -1f;
                ApplyIntro(1f);
            }
        }

        if (_urgency > 0 && !LobbyFx.ReducedMotion)
        {
            var hertz = _urgency >= 2 ? 1.6f : 0.75f;
            var pulse = 0.72f + 0.28f * LobbyFx.Pulse(_time, hertz);
            StartTime.Modulate = Color.White.WithAlpha(pulse);
        }
    }

    /// <summary>
    /// Подсвечивает отсчёт перед стартом раунда и ускоряет пульс на последних
    /// секундах. Цвет и частота зависят от оставшегося времени.
    /// </summary>
    public void SetCountdown(bool started, float seconds)
    {
        _countdownSeconds = started ? -1f : seconds;
        RefreshDeployStatus();

        // В спокойном состоянии блок показывает версию, сборку и сервер;
        // отсчёт подключается на последних минутах перед сменой и во время раунда.
        StartTime.Visible = started || (seconds > 0f && seconds <= 180f);

        NodeBar.Fill = started || seconds <= 0f
            ? 1f
            : seconds >= 180f
                ? 0.65f
                : Math.Clamp(1f - seconds / 180f, 0.08f, 1f);

        var urgency = 0;

        if (!started)
        {
            if (seconds <= UrgentSeconds)
                urgency = 2;
            else if (seconds <= WarningSeconds)
                urgency = 1;
        }

        if (urgency == _urgency)
            return;

        _urgency = urgency;

        StartTime.FontColorOverride = urgency switch
        {
            2 => Color.FromHex("#FF3B47"),
            1 => Color.FromHex("#E8A33D"),
            _ => null,
        };

        if (urgency == 0 || LobbyFx.ReducedMotion)
            StartTime.Modulate = Color.White;
    }

    private void UpdateTopBar()
    {
        TopTime.Text = DateTime.Now.ToString("HH:mm");

        var channel = _net.ServerChannel;
        TopPing.Text = channel != null && channel.Ping > 0
            ? Loc.GetString("ui-lobby-ping", ("ping", channel.Ping))
            : Loc.GetString("ui-lobby-ping-unknown");
    }

    public void SwitchState(LobbyGuiState state)
    {
        _state = state;

        DefaultState.Visible = false;
        CharacterSetupState.Visible = false;

        // Обучение живёт только в основном состоянии: уход в редактор персонажа
        // закрывает его, и при возврате оно не всплывает повторно.
        Tutorial.Visible = false;

        switch (state)
        {
            case LobbyGuiState.Default:
                DefaultState.Visible = true;
                _chatForcedOpen = false;
                UpdateResponsiveLayout();

                if (_readinessCleared)
                {
                    _readinessCleared = false;
                    ShowDeployNotice(Loc.GetString("ui-lobby-ready-cleared"));
                }
                break;
            case LobbyGuiState.CharacterSetup:
                CharacterSetupState.Visible = true;
                _chatForcedOpen = false;
                ChatGlass.Visible = false;
                Chat.Visible = false;
                ChatStrip.Visible = false;
                UserInterfaceManager.GetUIController<LobbyUIController>().ReloadCharacterSetup();
                break;
        }
    }

