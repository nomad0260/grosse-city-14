    /// <summary>
    /// Renders the single deployment state used by both the highlighted menu
    /// row and the ready plaque. Keeping them on one state prevents the row,
    /// the plaque and their disabled flags from drifting apart.
    /// </summary>
    public void SetDeployState(bool ready, bool lateJoin, bool disabled, string? reason)
    {
        _deployReady = ready;
        _deployLateJoin = lateJoin;
        _deployDisabled = disabled;
        _deployReason = reason ?? string.Empty;

        ReadyButton.ToggleMode = !lateJoin;
        ReadyButton.Disabled = disabled;
        DeployMenuRow.Disabled = disabled;

        SetReadyPressed(!lateJoin && ready);
        if (lateJoin)
        {
            ReadyKicker.Text = Loc.GetString("ui-lobby-deploy-kicker-latejoin");
            ReadyLabel.Text = Loc.GetString("ui-lobby-deploy-action-latejoin");
            ReadySubLabel.Text = Loc.GetString("ui-lobby-deploy-sub-latejoin");
        }

        DeployReason.Text = _deployReason;
        DeployReason.Visible = disabled && !string.IsNullOrEmpty(_deployReason);
        ReadyButton.ToolTip = disabled ? _deployReason : null;
        DeployMenuRow.ToolTip = disabled ? _deployReason : null;
        RefreshDeployStatus();
    }

    private void RefreshDeployStatus()
    {
        if (_noticeTimer > 0f)
        {
            DeployStatus.Text = _noticeText;
            DeployStatus.Visible = true;
            return;
        }

        if (_deployDisabled || !_deployReady && !_deployLateJoin)
        {
            DeployStatus.Visible = false;
            return;
        }

        if (_deployLateJoin)
        {
            DeployStatus.Text = Loc.GetString("ui-lobby-deploy-open");
            DeployStatus.Visible = true;
            return;
        }

        DeployStatus.Text = _countdownSeconds > 0f && _countdownSeconds < 3600f
            ? Loc.GetString("ui-lobby-deploy-queued-in", ("time", FormatCountdown(_countdownSeconds)))
            : Loc.GetString("ui-lobby-deploy-queued");
        DeployStatus.Visible = true;
    }

