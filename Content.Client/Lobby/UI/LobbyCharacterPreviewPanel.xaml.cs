using System;
using Content.Shared.Humanoid.Prototypes;
using Content.Shared.Localizations;
using Content.Shared.Preferences;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;
using Robust.Shared.Prototypes;

namespace Content.Client.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class LobbyCharacterPreviewPanel : Control
{
    [Dependency] private IPrototypeManager _prototypeManager = default!;
    public LobbyCharacterPreviewPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        ProfilePreviewSpriteView.ToolTip = Loc.GetString("ui-lobby-dossier-rotate-hint");
    }

    public void SetLoaded(bool value)
    {
        Loaded.Visible = value;
        Unloaded.Visible = !value;
        Status.Text = Loc.GetString(value ? "ui-lobby-dossier-status-active" : "ui-lobby-dossier-status-unloaded");
    }

    public void SetDossier(string name, int age, string species, string job, int slot)
    {
        DossierNameLabel.Text = string.IsNullOrWhiteSpace(name)
            ? "—"
            : name.Trim();
        AgeValue.Text = age.ToString();
        SpeciesValue.Text = string.IsNullOrWhiteSpace(species)
            ? "—"
            : species;
        JobValue.Text = string.IsNullOrWhiteSpace(job)
            ? "—"
            : job;
        FileId.Text = $"FILE-{slot + 1:D2}";

        PlaytimeValue.Text = "—";
        ShiftsValue.Text = "—";
        EquipmentValue.Text = "—";
    }

    /// <summary>
    /// Fills the service record with data the client already has. Overall
    /// playtime comes from the server playtime trackers.
    /// </summary>
    public void SetServiceRecord(TimeSpan overallPlaytime)
    {
        PlaytimeValue.Text = overallPlaytime > TimeSpan.Zero
            ? ContentLocalizationManager.FormatPlaytime(overallPlaytime)
            : "—";

        // The server does not send a per-player shift counter to the lobby.
        ShiftsValue.Text = "—";
    }

    /// <summary>
    /// Заполняет досье из выбранного профиля персонажа.
    /// </summary>
    public void SetDossier(HumanoidCharacterProfile profile, int slot)
    {
        var species = _prototypeManager.TryIndex(profile.Species, out SpeciesPrototype? speciesProto)
            ? Loc.GetString(speciesProto.Name)
            : profile.Species.Id;

        JobPrototype? selectedJob = null;

        foreach (var (jobId, priority) in profile.JobPriorities)
        {
            if (!_prototypeManager.TryIndex(jobId, out JobPrototype? jobProto))
                continue;

            if (priority == JobPriority.High)
            {
                selectedJob = jobProto;
                break;
            }

            selectedJob ??= jobProto;
        }

        var job = selectedJob != null ? Loc.GetString(selectedJob.Name) : "—";

        SetDossier(profile.Name, profile.Age, species, job, slot);

        var selectedItems = 0;
        foreach (var role in profile.Loadouts.Values)
        {
            foreach (var group in role.SelectedLoadouts.Values)
                selectedItems += group.Count;
        }

        EquipmentValue.Text = selectedItems > 0
            ? Loc.GetString("ui-lobby-dossier-equipment-custom", ("count", selectedItems))
            : Loc.GetString("ui-lobby-dossier-equipment-standard");
    }

    public void ClearDossier()
    {
        DossierNameLabel.Text = "—";
        AgeValue.Text = "—";
        SpeciesValue.Text = "—";
        JobValue.Text = "—";
        FileId.Text = "FILE-—";
        PlaytimeValue.Text = "—";
        ShiftsValue.Text = "—";
        EquipmentValue.Text = "—";
    }
}
