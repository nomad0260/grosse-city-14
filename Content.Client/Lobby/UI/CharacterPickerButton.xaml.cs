namespace Content.Client.Lobby.UI;

/// <summary>
/// Holds character data on the side of the setup GUI.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CharacterPickerButton : ContainerButton
{
    private static readonly Color BaseBg = Color.FromHex("#151817");
    private static readonly Color ActiveBg = Color.FromHex("#1F2322");
    private static readonly Color Steel = Color.FromHex("#777970");
    private static readonly Color RedAccent = Color.FromHex("#D13239");

    private float _hover;
    private bool _wasHovered;

    /// <summary>
    /// Invoked if we should delete the attached character
    /// </summary>
    public event Action? OnDeletePressed;

    public CharacterPickerButton(
        IPrototypeManager prototypeManager,
        ISharedPlayerManager playerMan,
        ButtonGroup group,
        HumanoidCharacterProfile profile,
        bool isSelected)
    {
        RobustXamlLoader.Load(this);
        StyleBoxOverride = new StyleBoxFlat(Color.Transparent)
        {
            ContentMarginLeftOverride = 8,
            ContentMarginRightOverride = 8,
            ContentMarginTopOverride = 4,
            ContentMarginBottomOverride = 4,
        };
        ToggleMode = true;
        Group = group;
        OnPressed += _ => LobbyFx.PlayClick();

        var deleteStyle = new StyleBoxFlat
        {
            BackgroundColor = LobbyFx.GraphiteDark.WithAlpha(0.58f),
            BorderColor = Steel.WithAlpha(0.35f),
            BorderThickness = new Thickness(1f),
            ContentMarginLeftOverride = 8,
            ContentMarginRightOverride = 8,
        };
        DeleteButton.StyleBoxOverride = deleteStyle;
        DeleteButton.OnMouseEntered += _ => LobbyFx.PlayHover();
        DeleteButton.OnPressed += _ => LobbyFx.PlayClick();
        ConfirmDeleteButton.StyleBoxOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex("#2A1214").WithAlpha(0.78f),
            BorderColor = RedAccent,
            BorderThickness = new Thickness(1f),
            ContentMarginLeftOverride = 8,
            ContentMarginRightOverride = 8,
        };
        ConfirmDeleteButton.OnMouseEntered += _ => LobbyFx.PlayHover();
        var description = profile.Name;

        View.LoadPreview(profile);

        var highPriorityJob = profile.JobPriorities.SingleOrDefault(p => p.Value == JobPriority.High).Key;
        if (highPriorityJob != default)
        {
            var jobName = prototypeManager.Index(highPriorityJob).LocalizedName;
            description = $"{description}\n{jobName}";
        }

        Pressed = isSelected;
        DeleteButton.Visible = !isSelected;

        DescriptionLabel.Text = description;

        ConfirmDeleteButton.OnPressed += _ =>
        {
            LobbyFx.PlayClick();
            Parent?.RemoveChild(this);
            Parent?.RemoveChild(ConfirmDeleteButton);
            OnDeletePressed?.Invoke();
        };

        DeleteButton.OnPressed += _ =>
        {
            DeleteButton.Visible = false;
            ConfirmDeleteButton.Visible = true;
        };
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        var hovered = !Disabled && IsHovered;
        if (hovered && !_wasHovered)
            LobbyFx.PlayHover();

        _wasHovered = hovered;
        _hover = LobbyFx.Approach(_hover, hovered ? 1f : 0f, 14f, args.DeltaSeconds);
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        var size = new Vector2(PixelSize.X, PixelSize.Y);
        if (size.X > 0f && size.Y > 0f)
        {
            var emphasis = Pressed ? 1f : _hover * 0.7f;
            var bg = Color.InterpolateBetween(BaseBg.WithAlpha(0.46f), ActiveBg.WithAlpha(0.74f), emphasis);
            handle.DrawRect(new UIBox2(0f, 0f, size.X, size.Y), bg);

            var border = Pressed
                ? RedAccent.WithAlpha(0.80f)
                : Color.InterpolateBetween(Steel.WithAlpha(0.32f), RedAccent.WithAlpha(0.60f), _hover);
            handle.DrawRect(new UIBox2(0f, 0f, size.X, 1f), border);
            handle.DrawRect(new UIBox2(0f, size.Y - 1f, size.X, size.Y), border);
            handle.DrawRect(new UIBox2(size.X - 1f, 0f, size.X, size.Y), border);

            var leftBar = Pressed ? RedAccent : Color.InterpolateBetween(Steel.WithAlpha(0.45f), RedAccent, _hover);
            handle.DrawRect(new UIBox2(0f, 0f, Pressed ? 3.5f : 2f + _hover, size.Y), leftBar);
        }

        base.Draw(handle);
    }
}
