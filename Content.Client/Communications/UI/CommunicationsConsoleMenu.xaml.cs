using System.Globalization;
using Content.Client.UserInterface.Controls;
using Content.Shared._Grosse.WorkPhase;    //Grosse-edit
using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client.Communications.UI
{
    [GenerateTypedNameReferences]
    public sealed partial class CommunicationsConsoleMenu : FancyWindow
    {
        [Dependency] private IConfigurationManager _cfg = default!;
        [Dependency] private IGameTiming _timing = default!;
        [Dependency] private ILocalizationManager _loc = default!;

        public bool CanAnnounce;
        public bool CanBroadcast;
        public bool CanCall;
        public bool AlertLevelSelectable;
        public bool CountdownStarted;
        public string CurrentLevel = string.Empty;
        public TimeSpan? CountdownEnd;
        public bool HasWorkPhase;    //Grosse-edit-start
        public TimeSpan? PhaseEnd;

        private WorkPhase? _listedPhase;
        private int _shownWorkMinutes = -1;
        private int _shownFreeMinutes = -1;    //Grosse-edit-end

        public event Action? OnEmergencyLevel;
        public event Action<string>? OnAlertLevel;
        public event Action<WorkPhase>? OnWorkPhase;    //Grosse-edit
        public event Action<int, int>? OnApplyPhaseTime;    //Grosse-edit
        public event Action<string>? OnAnnounce;
        public event Action<string>? OnBroadcast;

        public CommunicationsConsoleMenu()
        {
            IoCManager.InjectDependencies(this);
            RobustXamlLoader.Load(this);

            MessageInput.Placeholder = new Rope.Leaf(_loc.GetString("comms-console-menu-announcement-placeholder"));

            var maxAnnounceLength = _cfg.GetCVar(CCVars.ChatMaxAnnouncementLength);
            MessageInput.OnTextChanged += (args) =>
            {
                if (args.Control.TextLength > maxAnnounceLength)
                {
                    AnnounceButton.Disabled = true;
                    AnnounceButton.ToolTip = Loc.GetString("comms-console-message-too-long");
                }
                else
                {
                    AnnounceButton.Disabled = !CanAnnounce;
                    AnnounceButton.ToolTip = null;

                }
            };

            AnnounceButton.OnPressed += _ => OnAnnounce?.Invoke(Rope.Collapse(MessageInput.TextRope));
            AnnounceButton.Disabled = !CanAnnounce;

            BroadcastButton.OnPressed += _ => OnBroadcast?.Invoke(Rope.Collapse(MessageInput.TextRope));
            BroadcastButton.Disabled = !CanBroadcast;

            AlertLevelButton.OnItemSelected += args =>
            {
                var metadata = AlertLevelButton.GetItemMetadata(args.Id);
                if (metadata != null && metadata is string cast)
                {
                    OnAlertLevel?.Invoke(cast);
                }
            };


            AlertLevelButton.Disabled = !AlertLevelSelectable;

            WorkDuration.IsValid = static minutes => minutes is >= WorkPhases.MinMinutes and <= WorkPhases.MaxMinutes;    //Grosse-edit-start
            FreeDuration.IsValid = static minutes => minutes is >= WorkPhases.MinMinutes and <= WorkPhases.MaxMinutes;

            PhaseButton.OnItemSelected += args =>
            {
                if (PhaseButton.GetItemMetadata(args.Id) is WorkPhase phase)
                    OnWorkPhase?.Invoke(phase);
            };

            ApplyPhaseTimeButton.OnPressed += _ => OnApplyPhaseTime?.Invoke(WorkDuration.Value, FreeDuration.Value);
                //Grosse-edit-end
            EmergencyShuttleButton.OnPressed += _ => OnEmergencyLevel?.Invoke();
            EmergencyShuttleButton.Disabled = !CanCall;
        }

        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);
            UpdateCountdown();
            UpdatePhaseCountdown();    //Grosse-edit
        }

        // The current alert could make levels unselectable, so we need to ensure that the UI reacts properly.
        // If the current alert is unselectable, the only item in the alerts list will be
        // the current alert. Otherwise, it will be the list of alerts, with the current alert
        // selected.
        public void UpdateAlertLevels(List<string>? alerts, string currentAlert)
        {
            AlertLevelButton.Clear();

            if (alerts == null)
            {
                var name = currentAlert;
                if (_loc.TryGetString($"alert-level-{currentAlert}", out var locName))
                {
                    name = locName;
                }
                AlertLevelButton.AddItem(name);
                AlertLevelButton.SetItemMetadata(AlertLevelButton.ItemCount - 1, currentAlert);
            }
            else
            {
                foreach (var alert in alerts)
                {
                    var name = alert;
                    if (_loc.TryGetString($"alert-level-{alert}", out var locName))
                    {
                        name = locName;
                    }
                    AlertLevelButton.AddItem(name);
                    AlertLevelButton.SetItemMetadata(AlertLevelButton.ItemCount - 1, alert);
                    if (alert == currentAlert)
                    {
                        AlertLevelButton.Select(AlertLevelButton.ItemCount - 1);
                    }
                }
            }
        }

        public void UpdateCountdown()
        {
            if (!CountdownStarted)
            {
                CountdownLabel.SetMessage(string.Empty);
                EmergencyShuttleButton.Text = Loc.GetString("comms-console-menu-call-shuttle");
                return;
            }

            var diff = MathHelper.Max((CountdownEnd - _timing.CurTime) ?? TimeSpan.Zero, TimeSpan.Zero);

            EmergencyShuttleButton.Text = Loc.GetString("comms-console-menu-recall-shuttle");
            var infoText = Loc.GetString($"comms-console-menu-time-remaining",
                ("time", diff.ToString(@"hh\:mm\:ss", CultureInfo.CurrentCulture)));
            CountdownLabel.SetMessage(infoText);
        }
            //Grosse-edit-start
        public void UpdateWorkPhase(bool hasWorkPhase, WorkPhase current, TimeSpan? phaseEnd, int workMinutes, int freeMinutes)
        {
            HasWorkPhase = hasWorkPhase;
            PhaseSection.Visible = hasWorkPhase;
            PhaseEnd = phaseEnd;

            if (!hasWorkPhase)
                return;

            if (workMinutes != _shownWorkMinutes)
            {
                WorkDuration.OverrideValue(workMinutes);
                _shownWorkMinutes = workMinutes;
            }

            if (freeMinutes != _shownFreeMinutes)
            {
                FreeDuration.OverrideValue(freeMinutes);
                _shownFreeMinutes = freeMinutes;
            }

            if (_listedPhase != current || PhaseButton.ItemCount == 0)
            {
                PhaseButton.Clear();
                foreach (var phase in new[] { WorkPhase.Free, WorkPhase.Work, WorkPhase.Curfew })
                {
                    PhaseButton.AddItem(Loc.GetString(WorkPhases.Name(phase)));
                    PhaseButton.SetItemMetadata(PhaseButton.ItemCount - 1, phase);
                    if (phase == current)
                        PhaseButton.Select(PhaseButton.ItemCount - 1);
                }

                _listedPhase = current;
            }

            UpdatePhaseCountdown();
        }

        public void UpdatePhaseCountdown()
        {
            if (!HasWorkPhase)
                return;

            if (PhaseEnd == null)
            {
                PhaseTimeLabel.Text = Loc.GetString("comms-console-menu-phase-until-lifted");
                return;
            }

            var diff = MathHelper.Max(PhaseEnd.Value - _timing.CurTime, TimeSpan.Zero);
            PhaseTimeLabel.Text = Loc.GetString("comms-console-menu-phase-time-remaining",
                ("time", WorkPhases.FormatRemaining(diff)));
        }    //Grosse-edit-end
    }
}
